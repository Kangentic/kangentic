/** What a session did when the move ends it, for the wait's log line. */
const OWN_MOVE_CALL = 'moved its own task';

/**
 * Before a move ends a session: when that session is the one whose
 * `kangentic_move_task` call started the move, wait for the turn that made the
 * call to end (`own-call-turn-wait.ts`). Returns whether it waited.
 */
async function waitIfOwnAgentSession(
  context: IpcContext,
  ownAgentSessionId: string | null,
  endingSessionId: string,
  signal: AbortSignal,
): Promise<boolean> {
  if (ownAgentSessionId !== endingSessionId) return false;
  await waitForOwnAgentTurn(context.sessionManager, endingSessionId, OWN_MOVE_CALL, signal);
  return true;
}

/**
 * Suspend a live PTY session so Phase 3 can respawn it with new CLI flags:
 * emit a spawn-progress label naming the handoff, capture metrics while
 * caches are populated, mark the DB record suspended (or exited for queued
 * records that never started), suspend the PTY, and clear task.session_id.
 * Shared by all four same-column respawn triggers: a model change, an
 * effort change to a concrete value, a session-track switch (isolated
 * column entry/exit or `always_spawn_new`), and a cross-agent handoff.
 *
 * `phase` is required, not optional: every caller must name what the user
 * is about to see instead of the suspended session's stale "Paused" state,
 * so a future respawn branch cannot silently opt out of labeling its own
 * window (see the flash bug this fixes - the suspend used to leave the
 * card and task detail reading "Paused"/"Resume session" for the entire
 * unlocked Phase 2 gap). Emitted as the FIRST statement, before the record
 * is even marked suspended: while the session is still 'running',
 * getTaskProgress lets it own the display (task-progress.ts:166 applies a
 * label only when there is no session or the session is 'suspended'), so the
 * early emit is inert until the suspend actually lands and is never a source
 * of its own gap.
 *
 * `ownAgentSessionId` and `signal` are required for the same reason: the
 * session this ends may be the one whose `kangentic_move_task` call started
 * the move, and that session ends only once its turn does.
 */
async function suspendLiveSessionForRespawn(args: {
  context: IpcContext;
  tasks: ReturnType<typeof getProjectRepos>['tasks'];
  sessionRepo: SessionRepository;
  usageHistoryRepo: UsageHistoryRepository;
  taskId: string;
  liveSessionId: string;
  record: SessionRecord | undefined | null;
  task: Task;
  projectPath: string | null;
  defaultBaseBranch: string;
  phase: SpawnPhase;
  ownAgentSessionId: string | null;
  signal: AbortSignal;
  // `session_id` is excluded, not merely omitted by convention: it is spread
  // after `session_id: null` below, so a caller that passed one would silently
  // defeat the null-out this helper exists to guarantee.
  additionalTaskUpdates?: Partial<Omit<TaskUpdateInput, 'id' | 'session_id'>>;
}): Promise<void> {
  const { context, tasks, sessionRepo, usageHistoryRepo, taskId, liveSessionId, record, task, projectPath, defaultBaseBranch, phase, ownAgentSessionId, signal, additionalTaskUpdates } = args;
  // Ahead of the label: the caller's session is still running its turn.
  const waited = await waitIfOwnAgentSession(context, ownAgentSessionId, liveSessionId, signal);
  // The wait can last seconds, and the session may exit in it, so a record
  // read before it is read again.
  const currentRecord = waited ? resolveOwnSessionRecord(sessionRepo, liveSessionId, taskId) : record;
  emitSpawnProgress(context.mainWindow, taskId, phase);
  // Everything after the emit runs in Phase 1, INSIDE the withTaskLock call.
  // That call sits under a try whose only clause is a `finally` (the
  // AbortController cleanup); the catch that retires labels belongs to a
  // separate, later try covering Phase 2/3 only. So a throw here - a rejecting
  // sessionManager.suspend, or a locked-DB markRecordSuspended / tasks.update -
  // would escape handleTaskMove entirely and strand the label just emitted
  // until the 120s TTL. Clear it and rethrow so the caller's behavior is
  // otherwise unchanged.
  //
  // This retires the LABEL only. A throw partway through still leaves the DB
  // half-written (record marked suspended without session_id cleared, or the
  // reverse); Phase 1 has no rollback and that is unchanged here.
  try {
    if (currentRecord && currentRecord.agent_session_id
        && (currentRecord.status === 'running' || currentRecord.status === 'exited')) {
      captureSessionMetrics(
        context.sessionManager,
        sessionRepo,
        usageHistoryRepo,
        liveSessionId,
        currentRecord.id,
        currentRecord.started_at,
        currentRecord.session_type,
      );
      refineTranscriptTokens(context.sessionManager, sessionRepo, liveSessionId, currentRecord.id);
      refineTranscriptToolCounts(context.sessionManager, sessionRepo, liveSessionId, currentRecord.id);
      captureGitChurn(task, sessionRepo, usageHistoryRepo, currentRecord.id, projectPath, defaultBaseBranch);
      markRecordSuspended(sessionRepo, currentRecord.id, 'system');
    } else if (currentRecord && currentRecord.status === 'queued') {
      markRecordExited(sessionRepo, currentRecord.id);
    }
    await context.sessionManager.suspend(liveSessionId);
    tasks.update({ id: taskId, session_id: null, ...additionalTaskUpdates });
  } catch (error) {
    clearSpawnProgress(context.mainWindow, taskId);
    throw error;
  }
}

/**
 * Core task-move logic shared by the TASK_MOVE IPC handler and the
 * plan-exit auto-move listener. Moves the task, runs transitions, and
 * manages session lifecycle based on the target column's role.
 */
/**
 * Plan returned from Phase 1 when the move needs a subsequent worktree +
 * spawn. Priorities 1 / 2 / 2.5 / 3b / 3c handle the entire move under the
 * Phase 1 lock and return null; only Priority 3a (handoff) and Priority 4
 * (no active session) carry through to Phase 2/3.
 */
type MoveSpawnPlan = {
  task: Task;
  fromSwimlaneId: string;
  /**
   * The SOURCE lane the task lived in before this move, captured at Phase 1.
   * Threaded to spawnAgent as `settingsSourceLane`: the first-spawn override
   * lock resolves still-inherited Advanced fields against the lane the user
   * configured the task in, never the destination column. Required (not
   * optional) so every plan-return site threads it through explicitly.
   */
  fromLane: Swimlane | undefined;
  originalPosition: number;
  toLane: Swimlane | undefined;
  skipPromptTemplate: boolean;
  resolvedProjectId: string;
  resolvedProjectPath: string | null;
  /**
   * Delivered as the resumed session's next message by spawnAgent's fallback
   * when the destination column has no auto_command. Set by the plan-exit
   * auto-move so a respawned session does not sit idle. Required (not optional)
   * so every return site that builds a plan must thread it through explicitly;
   * a new respawn sub-case that forgets it is a compile error, not a silent
   * dropped continuation.
   */
  continuationPrompt: string | undefined;
  /**
   * Recovery move out of Done: spawnAgent must resume the session WITHOUT
   * injecting the destination column's auto_command. Required (not optional) so
   * every plan-return site threads it through explicitly; a new respawn sub-case
   * that forgets it is a compile error, not a silently-injected command on a
   * restore. See spawnAgent's `suppressAutoCommand`.
   */
  suppressAutoCommand: boolean;
};

/**
 * Who asked for this move. Required (not optional, and never a field on the
 * `options` bag) so a new call site cannot forget it: adding a caller without
 * naming its origin is a compile error, not a board that silently goes stale.
 *
 * This exists because `handleTaskMove` used to announce nothing at all, leaving
 * each caller to fan out the notifications itself. Three of the four got it
 * wrong in different ways, and the mobile bridge did neither half - a task moved
 * from the phone left the desktop board rendering the card in its old column
 * indefinitely.
 */
export type TaskMoveOrigin = 'renderer' | 'agent' | 'mobile' | 'auto-move' | 'automation' | 'workflow';

type MovePush = (context: IpcContext, projectId: string, input: { taskId: string; targetSwimlaneId: string }, title: string) => void;

/**
 * The renderer push for each origin once the move has settled, or null for
 * "say nothing". The commit point sends its own, quiet, push first
 * (`MOVE_COMMIT_PUSH_BY_ORIGIN`). That table reuses the `mobile`,
 * `automation` and `workflow` entries here, so they must stay toast-free.
 *
 * A `Record` rather than a switch so a new `TaskMoveOrigin` member is a compile
 * error here too. The asymmetry is deliberate:
 *
 * - `renderer` is silent because it initiated the move and already updated
 *   optimistically. Pushing would cost a redundant board reload, and on the
 *   agent channel the user would toast themselves.
 * - `mobile` gets its own QUIET channel rather than reusing
 *   TASK_UPDATED_BY_AGENT, whose listener toasts `Task updated by agent`. No
 *   agent touched a task the user dragged on their own phone.
 *
 * The board-changed bus emit is NOT part of this table: it is unconditional for
 * every origin. See the announce block at the end of `handleTaskMove` for why.
 */
const MOVE_PUSH_BY_ORIGIN: Record<TaskMoveOrigin, MovePush | null> = {
  renderer: null,
  agent: (context, projectId, input, title) =>
    sendToRenderer(context.mainWindow, IPC.TASK_UPDATED_BY_AGENT, input.taskId, title, projectId),
  mobile: (context, projectId) =>
    sendToRenderer(context.mainWindow, IPC.TASK_MOVED_BY_MOBILE, projectId),
  'auto-move': (context, projectId, input, title) =>
    sendToRenderer(context.mainWindow, IPC.TASK_AUTO_MOVED, input.taskId, input.targetSwimlaneId, title, projectId),
  // A Move to column automation and a workflow step are Kangentic acting on its
  // own. Quiet: a workflow can move many cards an hour, and the run log (or the
  // workflow view) is where "why did this move" is answered.
  automation: (context, projectId) =>
    sendToRenderer(context.mainWindow, IPC.TASK_MOVED_BY_AUTOMATION, projectId),
  workflow: (context, projectId) =>
    sendToRenderer(context.mainWindow, IPC.TASK_MOVED_BY_AUTOMATION, projectId),
};

/**
 * The renderer push for each origin at the commit point, before any slow work,
 * or null for "say nothing". Every one is a quiet board reload, so the card
 * leaves its old column the moment the row lands. Without it the board read
 * the task in its old column through a Done move's own-call turn wait,
 * suspend, reap and worktree removal: an agent's move of its own task to Done
 * kept the card there, unarchived, for 25 s, and its paused session offered a
 * Resume that main then refused.
 *
 * `agent` and `auto-move` reload on `TASK_SESSION_RESYNC` here because their
 * own channels toast, and the toast stays with the settle-time push, once per
 * move. `renderer` moved the card itself.
 */
const quietBoardReload: MovePush = (context, projectId) =>
  sendToRenderer(context.mainWindow, IPC.TASK_SESSION_RESYNC, projectId);

const MOVE_COMMIT_PUSH_BY_ORIGIN: Record<TaskMoveOrigin, MovePush | null> = {
  renderer: null,
  agent: quietBoardReload,
  mobile: MOVE_PUSH_BY_ORIGIN.mobile,
  'auto-move': quietBoardReload,
  automation: MOVE_PUSH_BY_ORIGIN.automation,
  workflow: MOVE_PUSH_BY_ORIGIN.workflow,
};

export async function handleTaskMove(
  context: IpcContext,
  input: { taskId: string; targetSwimlaneId: string; targetPosition: number },
  origin: TaskMoveOrigin,
  projectId?: string | null,
  projectPath?: string | null,
  // Kept out of `input` (which flows raw from the renderer over IPC) so the
  // renderer cannot inject prompts; only main-process callers (the plan-exit
  // listener) can pass a continuation.
  //
  // `onCommitted` fires the moment the board row is on disk (see the commit
  // point inside Phase 1), which is long before the returned promise settles:
  // a Done move suspends, reaps and deletes the worktree after that point, and
  // an auto-spawn move creates a worktree and spawns. A caller that has to
  // answer someone on a deadline (the mobile bridge verb, against the phone's
  // 10s per-verb budget) answers on this signal and lets the tail finish behind
  // the response. Every other caller keeps awaiting the whole move.
  //
  // `moveReason` is recorded on the move's `task_moves` row: the name of the
  // Move to column automation that made it, or a workflow's "Step done".
  //
  // `fromTurnEndGroup` marks a Move to column row's own move, which must not
  // stop the turn-end group that made it (`supersedeTurnEndWork`).
  //
  // `moverIsTaskAgent` says an `'agent'` move comes from the task's own agent
  // session, which a running workflow lets through (`workflowMoveRefusal`).
  //
  // `moverSessionId` names that session. When it is the task's live one and
  // the move ends it, the session ends only once its turn does
  // (`own-call-turn-wait.ts`), so the move stays in its own conversation.
  //
  // `expectedFromSwimlaneId` refuses the move unless the task is still in that
  // column once the lock lets it through. A Move to column row resolves its
  // target from its own column outside the lock, so a move that landed while
  // this one waited must not send the task on from a column it has left.
  //
  // `carriesMessage` says a message follows the move to the agent (a Move to
  // column row's Message, `kangentic_move_task`'s `message`). It usually holds
  // the reply the last column ended on, so a return to the main conversation
  // does not repeat that reply in its recap (`return-recap.ts`).
  options?: {
    continuationPrompt?: string;
    onCommitted?: () => void;
    moveReason?: string;
    fromTurnEndGroup?: boolean;
    moverIsTaskAgent?: boolean;
    moverSessionId?: string;
    expectedFromSwimlaneId?: string;
    carriesMessage?: boolean;
  },
): Promise<void> {
  // A workflow task's lock, asked BEFORE anything below aborts work in flight:
  // a refused drag must not cancel the workflow's own move of the same task.
  // Asked again inside the lock, against the reconciled row.
  const workflowCheck = (task: Task, checkProjectId: string): void => {
    const refusal = checkWorkflowMove(context, {
      projectId: checkProjectId,
      task,
      toSwimlaneId: input.targetSwimlaneId,
      origin,
      moverIsTaskAgent: options?.moverIsTaskAgent === true,
    });
    if (refusal) throw new Error(refusal);
  };
  const precheckProjectId = projectId ?? context.currentProjectId;
  if (precheckProjectId) {
    const precheckTask = readTaskForWorkflowPrecheck(precheckProjectId, input.taskId);
    if (precheckTask) workflowCheck(precheckTask, precheckProjectId);
  }

  // Abort any in-flight move or promotion BEFORE queueing on the lock - the
  // existing holder must see its abort and return so we can acquire the lock.
  abortInFlightMove(input.taskId);
  abortBacklogPromotion(input.taskId);
  // Turn-end work is superseded inside Phase 1, once the move is known to
  // change columns and the lock has let it through (see there): a reorder or a
  // refused move must not cancel a step check the idle agent will not repeat.
  const moveController = new AbortController();
  registerMoveController(input.taskId, moveController);
  const { signal } = moveController;

  // Tag every project-scoped log emitted across Phases 1-3 (worktree + spawn)
  // with the project this move targets, so concurrent moves on different
  // projects stay distinguishable in the dev terminal. Resolve the name from
  // the same id Phase 1 resolves; an unresolvable id (no project open) skips
  // the tag so the body inherits no misleading ambient context.
  const announceProjectId = projectId ?? context.currentProjectId;
  const logProjectName = announceProjectId
    ? context.projectRepo.getById(announceProjectId)?.name ?? null
    : null;

  // The board-changed bus emit, shared by the two announce points: once at the
  // commit point inside Phase 1, and once from the `finally` after the whole
  // move has settled. The rationale for announcing at all (and for erring
  // toward a duplicate) is on the settle-time block below; the rationale for
  // the commit-time one is at the commit point.
  //
  // `announceTaskBoardChange` carries the shutdown gate and the try/catch. The
  // gate is load-bearing rather than defensive: on that path the DB is already
  // closed and the window is going away, but the bus would still wake a phone
  // subscription mid-teardown. The catch matters because BoardEventBus is a
  // plain EventEmitter that dispatches synchronously on this stack, so a
  // subscriber that threw would either replace the error runMove is already
  // propagating, or turn a committed move into a rejection with the rest of
  // Phase 1 (the Done cleanup) skipped. Announcing is best-effort by design.
  const emitBoardChanged = (): void => {
    announceTaskBoardChange(context, announceProjectId, { change: 'task-updated', ids: [input.taskId] });
  };

  // Whether Phase 1's DB write actually landed, and the title captured with it.
  //
  // Both are set INSIDE the lock, on the line after the move + archive pair,
  // rather than where Phase 1 returns: Phase 1 crosses await boundaries after
  // the move (see the shutdown comment on the catch below), so a throw in that
  // window would otherwise lose a change that is already committed.
  //
  // The title has to be captured rather than read at announce time. `task` is
  // scoped to the Phase 1 closure and only escapes via the returned
  // MoveSpawnPlan, and Phase 1 returns null for every move it fully handles -
  // so on the common paths there is no task in scope by the time we announce.
  let moveCommitted = false;
  let movedTaskTitle = '';
  // Whether the task's workflow was running when this move passed its lock, for
  // a move no person made (an automation's, a plan exit's, the workflow's own).
  // Phase 3 starts no agent for one whose workflow was paused during Phase 2: the
  // turn that set it off belonged to a workflow that has since been set down.
  // A move a person's own work makes while the workflow is paused sees it paused
  // here, and starts its agent as on any card.
  let ranUnderRunningWorkflow = false;
  /**
   * The destination column's enter rows, on a move Phase 1 fully handles.
   *
   * Set inside the lock by the branches that keep or suspend a session and then
   * return, and RUN after the lock releases. Outside, deliberately: this is the
   * SHORT lock, and the group carries the adapters' own budgets, up to the five
   * minutes a `run_script` row can ask for. Running it inside would hold that
   * task's lock for the whole of it, which is the exact defect the run_script
   * rewrite removed, reached through a different door. Capping the group to the
   * exit budget instead was the other option and is worse: a script would then
   * mean one thing on a cold entry and another on a warm one.
   */
  let runEnterAutomations: (() => Promise<void>) | null = null;
  /**
   * Releases the mark a move by the task's own agent puts on that agent's
   * session at the commit (`markOwnCallSession`). Released when Phase 1
   * settles, by which point a session the move ends has ended.
   */
  let releaseOwnMoveMark: (() => void) | null = null;
  const runMove = async (): Promise<void> => {
  try {
    // === Phase 1 (locked, short) ===
    // All DB mutations and PTY kill/suspend dispatch for priorities 1-3.
    // Returns null when the move is fully handled inside Phase 1 (Priorities
    // 1, 2, 2.5, 3b, 3c), or a plan for Priority 3a / Priority 4 which need
    // slow worktree + spawn work in Phase 2/3.
    //
    // Short except for one bounded wait: a move by the task's own agent that
    // ends that agent's session first waits, up to OWN_CALL_TURN_WAIT_MS, for
    // the turn that made the move to end. A newer move of the task aborts it
    // before queueing here, which ends the wait; anything else that needs this
    // lock (a Pause, a Resume) queues behind it for at most that bound.
    const plan = await withTaskLock(input.taskId, async (): Promise<MoveSpawnPlan | null> => {
      const resolvedProjectId = projectId ?? context.currentProjectId;
      // Use !== undefined (not ??) to distinguish "caller passed null" from "caller omitted the arg"
      const resolvedProjectPath = projectPath !== undefined ? projectPath : context.currentProjectPath;
      if (!resolvedProjectId) throw new Error('No project is currently open');

      const { tasks, swimlanes, attachments } = getProjectRepos(context, resolvedProjectId);
      // The pointer every Priority branch below keys on, reconciled against the
      // registry FIRST. `task.session_id` outlives the session on a natural
      // exit: the exit listener marks the record `exited` but leaves the
      // pointer, so a CLI that ended on its own (an `/exit`, a crash, a
      // `--resume` whose transcript it could not read) left the task reading
      // as "has an active session". Priority 3 then kept that dead session
      // "alive" on every move and never spawned, with nothing but a To Do move
      // to recover (#682's rig hit it; any failed resume does). The same
      // helper `SESSION_RESUME` self-heals with: a pointer at a non-live row is
      // cleared, and a live PTY the pointer lost is re-linked, so a drifted
      // task neither skips its spawn nor spawns a duplicate. Synchronous, and
      // this lock is the one it asks its callers to hold.
      const { task } = reconcileTaskSessionRef(context, resolvedProjectId, input.taskId);
      // The session that asked for this move, when it is the task's live one.
      const ownAgentSessionId = options?.moverSessionId && task.session_id === options.moverSessionId
        ? task.session_id
        : null;

      const fromSwimlaneId = task.swimlane_id;
      const expectedFromSwimlaneId = options?.expectedFromSwimlaneId;
      if (expectedFromSwimlaneId !== undefined && fromSwimlaneId !== expectedFromSwimlaneId) {
        const expectedName = swimlanes.getById(expectedFromSwimlaneId)?.name ?? 'its column';
        throw new Error(`The task left ${expectedName} before it could be moved.`);
      }
      const originalPosition = task.position;
      const fromLane = swimlanes.getById(fromSwimlaneId);
      // Board Profiles: fold the task's profile over the destination column
      // ONCE, here, so every read below (agent resolution, the injection plan's
      // model/effort restart decision, auto_command) sees the
      // same profile-resolved strategy the cold spawn path uses.
      //
      // This path is the warm one - the destination already has a live session -
      // and it is where a half-wired profile does its quiet damage: the delta
      // check would compare the running session against the column's BASE model,
      // see no change, and leave the PTY on the previous column's rung while
      // spawnAgent would have switched it. Same task, different horsepower
      // depending on whether a session happened to be live.
      const rawToLane = swimlanes.getById(input.targetSwimlaneId);
      const toLane = applyProfileToLane(rawToLane, loadTaskProfile(context, task, resolvedProjectPath)) ?? rawToLane;

      // Only send the full prompt template (title + description + attachments) when
      // starting from To Do. Non-To Do sources are resuming previously-started
      // work, so re-sending the original description would duplicate context.
      const skipPromptTemplate = fromLane?.role !== 'todo';

      // Recovery move: the first move OUT of Done (whatever the destination)
      // resumes the session idle without injecting the destination column's
      // auto_command. The user is restoring the task to inspect it; the next
      // move injects per column config. See spawnAgent's `suppressAutoCommand`.
      const suppressAutoCommand = fromLane?.role === 'done';

      // The workflow lock, against the row as it is now (see the pre-check).
      workflowCheck(task, resolvedProjectId);
      ranUnderRunningWorkflow = !isMoveByAPerson(origin) && taskWorkflowState(task, resolvedProjectId) === 'running';

      // A move out of the column supersedes the task's turn-end work: a group
      // running for the column it is leaving, or a moved task's message still
      // waiting for an agent it is about to leave. Never a reorder within the
      // column, and never a refused move: the agent is idle, so no later turn
      // end would repeat a cancelled step check, and the task would sit there.
      // The turn-end group never holds this lock, so aborting it here is safe.
      if (fromSwimlaneId !== input.targetSwimlaneId) {
        supersedeTurnEndWork(input.taskId, { exceptOwnGroup: options?.fromTurnEndGroup });
      }

      // Move the task in the database, recording who moved it (the visit
      // boundary turn-end automations count from).
      tasks.move(input, { origin, reason: options?.moveReason ?? null });

      // Atomic archive for Done-role target: run synchronously in the same tick
      // as tasks.move so no reader can observe the intermediate state
      // (swimlane_id=Done, archived_at=NULL). better-sqlite3 is synchronous, so
      // a concurrent IPC handler cannot interleave SQL between these two calls.
      // Without this, a failure or hang in the downstream suspend/worktree-delete
      // leaves the task stuck as an active Done-column card.
      const isCrossColumnToDone = toLane?.role === 'done' && fromSwimlaneId !== input.targetSwimlaneId;
      if (isCrossColumnToDone) {
        tasks.archive(input.taskId);
        console.log(`[TASK_MOVE] Auto-archived task ${input.taskId.slice(0, 8)} (moved to Done)`);
      }

      // The inverse, in the same tick and for the same reason. A move OUT of
      // Done must clear the flag this handler set on the way in, or the task
      // lands in a live column while still archived: absent from the board
      // (every list query filters `archived_at IS NULL`) yet holding a worktree
      // and, in an auto-spawn column, a running agent. That is the same
      // "live agent with no card" state the Done/archived resume guard exists
      // to prevent, reached through a different door.
      //
      // The UI never takes this path - dragging or restoring an archived card
      // routes to TASK_UNARCHIVE - so this is reached by MCP `move_task` and
      // any other main-process caller of handleTaskMove.
      //
      // Keyed on the task's own flag rather than the source lane's role, so a
      // legacy archived row parked outside Done is repaired too. Moving WITHIN
      // Done keeps its archive (toLane is still the done role).
      // Truthiness, not `!== null`: a Task assembled without the column carries
      // `undefined`, and `!== null` would try to unarchive every ordinary move.
      if (Boolean(task.archived_at) && toLane?.role !== 'done') {
        tasks.clearArchived(input.taskId);
        console.log(`[TASK_MOVE] Unarchived task ${input.taskId.slice(0, 8)} (moved out of Done)`);
      }

      // A To Do move forgets the task's PR in the same tick as tasks.move, for
      // the archive's reason. The To Do branch below awaits the exit automations
      // and a cleanup that takes seconds on Windows (awaitExit, the reap, the
      // worktree removal), and a quit, crash or hang there used to leave the old
      // chip on a To Do card, its `merged` state blocking the next run's link.
      // Before the commit-time emit, so a paired phone's snapshot never carries
      // the old chip. `task` is the pre-move row, so the own-work gate reads the
      // task as it was; the exit automations get that same object, so their
      // `{{prUrl}}` is unchanged. Wrapped so a throw cannot skip the announce.
      const isCrossColumnToTodo = toLane?.role === 'todo' && fromSwimlaneId !== input.targetSwimlaneId;
      if (isCrossColumnToTodo) {
        try {
          forgetPRLinkOnTodoReset(context, tasks, task, resolvedProjectId);
        } catch (forgetError) {
          console.error(`[TASK_MOVE] Forgetting the PR link failed for task ${input.taskId.slice(0, 8)}:`, forgetError);
        }
      }

      // Messages held for the task's next agent are cleared by a move to Done
      // (the work ended) or To Do (a reset), in this same tick for the archive's
      // reason, and ahead of `supersedeMessageDeliveries` below, so a held
      // message mid-delivery finds its row already cleared and leaves it so.
      if (isCrossColumnToDone || isCrossColumnToTodo) {
        clearHeldMessages(resolvedProjectId, input.taskId);
      }

      // The board row has changed on disk from here on, so it must be announced
      // even if everything downstream fails. See the announce block after the
      // try/catch for why "the move threw" does not imply "nothing changed".
      moveCommitted = true;
      movedTaskTitle = task.title;
      // From the commit on, the turn that made this move belongs to the column
      // the task left, so its end is not judged for the new one: the exit rows
      // below can wait for that turn, and it lands while `session_id` still
      // names the caller. See `own-call-turn-wait.ts`.
      if (ownAgentSessionId && fromSwimlaneId !== input.targetSwimlaneId) {
        releaseOwnMoveMark = markOwnCallSession(ownAgentSessionId);
      }

      // Commit-time announce. Everything slow in this handler comes AFTER this
      // line, and much of it still inside this lock: the Done branch suspends,
      // reaps leftovers and deletes the worktree before Phase 1 returns, and
      // an auto-spawn destination pays for worktree creation and spawn in
      // Phases 2/3. Announcing only from the settle-time `finally` meant a
      // paired phone saw nothing until the desktop was completely done, so a
      // phone that had moved a card optimistically had no board snapshot to
      // settle against until its own verb timed out.
      //
      // The second bus emit from the `finally` is cheap: the Agent Monitor
      // debounces it into the push it already scheduled, and a paired phone
      // gets one more small board event, which it already tolerates (the
      // session-lifecycle feed double-emits by design). That second emit is
      // what corrects a committed-then-rolled-back move. Same row, same shape,
      // two emits.
      emitBoardChanged();
      // An open Workflows view shows where each of its tasks is.
      notifyWorkflowOfTask(task, announceProjectId);
      // Every move but the renderer's own has no optimistic renderer write
      // behind it, so without this the card sat in its old column until the
      // move settled: through a Done move's suspend, reap and worktree removal,
      // while the session view offered Resume on a task main had already
      // archived. Quiet for every origin (`MOVE_COMMIT_PUSH_BY_ORIGIN`): the
      // `agent` and `auto-move` toasts stay with the settle-time push, so the
      // pair costs one extra reload, never a second toast. Fenced like the
      // callback below, for the same reason, and silent once the quit has
      // begun, as the settle-time push is.
      if (announceProjectId && !isShuttingDown()) {
        try {
          MOVE_COMMIT_PUSH_BY_ORIGIN[origin]?.(context, announceProjectId, input, task.title);
        } catch (pushError) {
          console.error(`[TASK_MOVE] Commit-time push failed for task ${input.taskId.slice(0, 8)}:`, pushError);
        }
      }

      // Commit signal for a caller that answers on the row landing (the mobile
      // bridge verb). Bus first, so the board event is already queued on the
      // session before the verb response goes out. A caller's callback must
      // never turn a committed move into a rejection with the rest of this
      // branch (the Done cleanup) skipped, so it is fenced like the announce.
      if (options?.onCommitted) {
        try {
          options.onCommitted();
        } catch (callbackError) {
          console.error(`[TASK_MOVE] onCommitted callback threw for task ${input.taskId.slice(0, 8)}:`, callbackError);
        }
      }

      // Within-column reorder: no side effects needed
      if (fromSwimlaneId === input.targetSwimlaneId) return null;

      // The task is leaving its column, so a message that column is still
      // waiting to paste (a multi-line On task enter row, held for the agent's
      // turn to end) is no longer the column's to send. Keystroke bursts are
      // stopped by the scheduler's own cancel in the Priority branches below;
      // a paste never enters the scheduler, so it is stopped here. Not on the
      // reorder above: the task keeps its column, and with it its message.
      supersedeMessageDeliveries(task.id);

      // === Exit automations ===
      //
      // The SOURCE column's exit rows, here in Phase 1, inside the short lock,
      // after the DB write and the `board:changed` emit above and BEFORE the
      // Priority branches below. The position is load-bearing in both
      // directions: Priority 1 (To Do) kills the session, so an exit row that
      // needs the agent has to find it still attached; and the commit point is
      // already past, so a slow row cannot hold up the card the user dragged.
      //
      // An exit row NEVER aborts the move. The rollback at the end of this
      // handler reverts Phase 2 and Phase 3 only, which is why the announce
      // fires on `moveCommitted` rather than on success. Running rows here
      // after the commit point is safe precisely because the runner isolates
      // every row: a throw, a timeout, or the whole group failing records and
      // the move proceeds. Hence its own try/catch rather than joining the
      // surrounding one.
      //
      // The group is capped at EXIT_GROUP_BUDGET_MS in aggregate (the runner
      // applies it from the trigger), whatever the adapters declare, because
      // this is the SHORT lock and holding it is what wedges that task's next
      // move. That cap is a product statement, not a fudge: exit is for quick
      // handoffs, and long work belongs on enter, where Phase 3 already holds
      // the lock across the spawn and has a progress spinner to show for it.
      if (fromLane) {
        try {
          const exitRepos = getProjectRepos(context, resolvedProjectId);
          const exitSessionRepo = new SessionRepository(getProjectDb(resolvedProjectId));
          const exitEngine = createTransitionEngine(
            context,
            exitRepos.automations,
            exitRepos.automationRuns,
            exitRepos.tasks,
            exitSessionRepo,
            exitRepos.attachments,
            resolvedProjectId,
            resolvedProjectPath,
          );
          const exitSummary = await exitEngine.executeTransition(task, fromLane, 'exit', {
            signal,
            // No `startAgent`: on exit there is nothing to start. A row that
            // needs the agent and finds no session skips with that reason,
            // which the runner records.
            // AWAITED, unlike the enter path's, and the Priority branches
            // below are the reason: each opens with
            // `terminalSubmitScheduler.cancel(task.id)` before it kills,
            // suspends or re-points the session, so a burst merely SCHEDULED
            // here is cancelled mid-flight by this same move. See
            // `deliverExitMessage` for what that looked like in a preview.
            // A message with line breaks is pasted instead, awaited the same
            // way and handed `runSignal`, so the exit budget bounds it too.
            deliverToAgent: async (message, mode, runSignal) => {
              const liveSession = task.session_id;
              // The runner already skips an agent-needing row when the task
              // has no session, so reaching here without one means the row
              // does not need the agent. Nothing to deliver into.
              if (!liveSession) return;
              await deliverAgentMessageAndWait(context, {
                taskId: task.id,
                sessionId: liveSession,
                message,
                mode,
                verifier: resolveInjectionVerifier(task.agent, exitSessionRepo, task.id),
                signal: runSignal,
                turnWait: 'when-deferred',
              });
            },
            showNotification: (notification) => showAutomationNotification(context, notification),
            // The card names the row that is running. Without it a 60s exit
            // group looked like a card that simply took a long time to move.
            onProgress: createProgressCallback(context.mainWindow, task.id),
            fromColumn: fromLane,
            toColumn: toLane ?? null,
          });
          reportAutomationFailures(context, exitSummary, task, resolvedProjectId);

        } catch (exitError) {
          // Reaching here means the LIST could not run at all (a repository
          // read failed), not that a row failed. Either way the move goes on.
          console.error(`[TASK_MOVE] Exit automations failed for task ${input.taskId.slice(0, 8)}:`, exitError);
        } finally {
          // The exit group's own label, cleared by the group that set it.
          // Phase 3 has its own clear, but a move that returns from a Priority
          // branch never reaches Phase 3, so relying on it would strand the
          // last exit row's name on the card until the 120s TTL swept it.
          clearSpawnProgress(context.mainWindow, task.id);
        }
      }


      const db = getProjectDb(resolvedProjectId);
      const sessionRepo = new SessionRepository(db);
      const usageHistoryRepo = new UsageHistoryRepository(db);

      /**
       * Arm the DESTINATION column's enter rows for a move Phase 1 finishes.
       *
       * Every branch below that keeps or suspends a session returns straight out
       * of Phase 1, so without this the On enter group never ran on those moves
       * at all: only the cold spawn path (Priority 4, through `agent-spawn.ts`)
       * ever executed it. Measured in a preview: a task with a live session
       * moved into a column holding one enabled `notify` enter row produced NO
       * run record and no notification. A script or a webhook was equally dead.
       * The column's first message survived only because the live injection
       * delivers that one itself, which is exactly why its row is passed as
       * `alreadyDelivered` rather than sent twice.
       *
       * ARMED here, RUN after the lock releases. See `runEnterAutomations`.
       *
       * Message delivery inside it is fire and forget, unlike the exit hook's:
       * nothing after this point cancels the scheduler (Priority 3's own
       * `cancel` already ran, above the injection), and a message queues behind
       * that burst rather than racing it. A message with line breaks is pasted
       * instead, and waits for the agent's turn to end, which also keeps it from
       * racing that burst.
       *
       * No `startAgent`: on the keep-alive branches the session is live by
       * construction, and on the suspending one the column cannot hold a row
       * that needs an agent (`canColumnRun` blocks `send_message` wherever
       * "Start an agent here" is off). For a paused agent (`agentPaused`) a row
       * that needs it is skipped with that reason, and runs at its Resume.
       */
      const armEnterAutomations = (deliveredMessageId: string | null, agentPaused = false): void => {
        runEnterAutomations = async (): Promise<void> => {
        if (!toLane) return;
        try {
          const enterRepos = getProjectRepos(context, resolvedProjectId);
          const enterEngine = createTransitionEngine(
            context,
            enterRepos.automations,
            enterRepos.automationRuns,
            enterRepos.tasks,
            sessionRepo,
            enterRepos.attachments,
            resolvedProjectId,
            resolvedProjectPath,
          );
          const enterSummary = await enterEngine.executeTransition(task, toLane, 'enter', {
            signal,
            alreadyDelivered: deliveredMessageId ? new Set([deliveredMessageId]) : undefined,
            agentPaused,
            deliverToAgent: async (message, mode) => {
              // Re-read, never the Phase-1 snapshot. The enter group runs
              // OUTSIDE withTaskLock on purpose (a run_script row would
              // otherwise hold the lock for its whole budget), so between
              // arming and delivering, a Pause, a kill, or a natural agent exit
              // can take the now-free lock and null this task's session_id. The
              // move's own AbortSignal does not cover that: it fires only for a
              // superseding move. Delivering to the snapshot scheduled
              // keystrokes at a dead PTY and recorded the run as sent. Mirrors
              // agent-spawn.ts's deliverToAgent, which already re-reads.
              const currentTask = enterRepos.tasks.getById(task.id);
              const liveSession = currentTask?.session_id;
              if (!liveSession) return;
              // A one-line message is scheduled as keystrokes; one with line
              // breaks is pasted once the agent's turn ends, and a move out of
              // this column cancels it (`supersedeMessageDeliveries`).
              deliverAgentMessageInBackground(context, {
                taskId: task.id,
                sessionId: liveSession,
                message,
                mode,
                verifier: resolveInjectionVerifier(task.agent, sessionRepo, task.id),
                onOutcome: (report) => reportAutoCommandOutcome(context, tasks, task, report, resolvedProjectId),
              });
            },
            showNotification: (notification) => showAutomationNotification(context, notification),
            onProgress: createProgressCallback(context.mainWindow, task.id),
            fromColumn: fromLane ?? null,
            toColumn: toLane,
          });
          reportAutomationFailures(context, enterSummary, task, resolvedProjectId);
        } catch (enterError) {
          // The LIST could not run at all. The move is already committed and
          // the session is untouched, so it goes on, as on exit.
          console.error(`[TASK_MOVE] Enter automations failed for task ${input.taskId.slice(0, 8)}:`, enterError);
        } finally {
          // This group runs on the WARM path only, which by definition has no
          // spawn behind it, so Phase 3's clear never fires for it. Without
          // this the card kept the last row's name until the TTL.
          clearSpawnProgress(context.mainWindow, task.id);
        }
        };
      };
      // Resolved once per move and threaded into every git-churn capture site
      // below so they all resolve the base branch identically.
      const effectiveDefaultBranch = resolveDefaultBaseBranch(context, resolvedProjectPath);

      // Analytics: track critical-path transitions only.
      // Read agent from task.agent (set at spawn) and model from the latest
      // session record (the most recent run's CLI model id). Cost/duration/
      // token/tool metrics come from the LIFETIME summary aggregated across
      // every session row for the task (getSummaryForTask), so a task worked
      // across resume/suspend legs reports cumulative totals rather than just
      // the final leg - getLatestForTask alone would silently drop every
      // earlier leg's metrics. Any field may be missing (legacy rows, never
      // spawned, exited before any usage was recorded) - omit absent props.
      // These are properties on an existing event (budget-neutral), not new
      // events.
      if (toLane?.role === 'done') {
        const completeProps: Record<string, string | number | boolean> = {};
        if (task.agent) completeProps.agent = task.agent;
        const latestSessionRecord = sessionRepo.getLatestForTask(task.id);
        if (latestSessionRecord?.model_id) {
          completeProps.model = parseModelId(latestSessionRecord.model_id).baseId;
        }
        // The resolved mode the last session actually ran under (the task's
        // own permission_mode is a raw override, null = inherit).
        if (latestSessionRecord?.permission_mode) {
          completeProps.permissionMode = latestSessionRecord.permission_mode;
        }
        const lifetimeSummary = sessionRepo.getSummaryForTask(task.id);
        if (lifetimeSummary) {
          completeProps.durationSeconds = Math.round(lifetimeSummary.durationMs / 1000);
          completeProps.costUsd = Math.round(lifetimeSummary.totalCostUsd * 10000) / 10000;
          completeProps.inputTokens = lifetimeSummary.totalInputTokens;
          completeProps.outputTokens = lifetimeSummary.totalOutputTokens;
          completeProps.toolCalls = lifetimeSummary.toolCallCount;
        }
        trackEvent('task_complete', completeProps);
        trackMilestone('first_task_complete');
      }

      // --- Priority 1: TARGET IS TO DO → full reset (kill session, remove worktree, delete branch) ---
      if (toLane?.role === 'todo') {
        context.terminalSubmitScheduler.cancel(task.id);
        // Clear any lingering spawn progress label from an in-flight spawn
        // that was aborted by this move. The aborted move's catch block also
        // calls clearSpawnProgress, but doing it here too guarantees the
        // renderer's "Initializing..." indicator vanishes regardless of
        // whether the prior move reached its catch path.
        clearSpawnProgress(context.mainWindow, task.id);
        // Kill (but don't remove from map) any in-flight PTY session spawned
        // by a concurrent move that hasn't written session_id to the task
        // record yet. Using killByTaskId instead of removeByTaskId so the
        // session stays in the map - cleanupTaskResources needs it there for
        // awaitExit to wait for the process to actually die before removing
        // the worktree (Windows file handles aren't released until exit).
        // kill() always tags the exit intentional, so this deliberate hard
        // reset's non-zero force-kill exit never surfaces a false "Session
        // crashed" toast.
        context.sessionManager.killByTaskId(task.id);
        try {
          await cleanupTaskResources(context, task, tasks, resolvedProjectId, resolvedProjectPath);
        } finally {
          // The link went when the move committed. This second pass clears the
          // head_sha the cleanup just captured from the old checkout, which
          // Tier 3 would otherwise resolve the old PR from on a run with no
          // worktree. It pushes nothing, since no link is left to draw. In a
          // finally so that, when the commit-time pass threw, this one retries
          // the whole clear even if the cleanup threw too. Gated on the
          // pre-cleanup snapshot. Wrapped because a throw here would replace the
          // cleanup error the finally is already propagating.
          try {
            forgetPRLinkOnTodoReset(context, tasks, task, resolvedProjectId);
          } catch (forgetError) {
            console.error(`[TASK_MOVE] Forgetting the PR link failed for task ${task.id.slice(0, 8)}:`, forgetError);
          }
        }
        // Re-read the task to check if worktree_path was actually cleared
        const updatedTask = tasks.getById(task.id);
        if (updatedTask?.worktree_path) {
          console.warn(`[TASK_MOVE] Partial cleanup for task ${task.id.slice(0, 8)} (moved to To Do, session removed but worktree directory could not be deleted - will retry on next startup)`);
        } else {
          console.log(`[TASK_MOVE] Full cleanup for task ${task.id.slice(0, 8)} (moved to To Do, session + worktree + branch removed)`);
        }
        // Schedule background prune to clean up stale git worktree metadata
        if (resolvedProjectPath) {
          WorktreeManager.scheduleBackgroundPrune(resolvedProjectPath);
        }
        return null;
      }

      // --- Priority 2: TARGET IS DONE → suspend + archive (resumable on unarchive) ---
      if (toLane?.role === 'done') {
        context.terminalSubmitScheduler.cancel(task.id);
        // A genuine park, not a respawn: retire any label a prior in-flight
        // spawn left behind (the same reasoning as Priority 1's clear above).
        // Without this, the renderer's suspended-row carve-out (added for the
        // handoff flash fix) would keep showing that stale label instead of
        // "Paused" through the whole archive below.
        clearSpawnProgress(context.mainWindow, task.id);
        if (task.session_id) {
          // A session that moved its own task here ends once its turn does.
          await waitIfOwnAgentSession(context, ownAgentSessionId, task.session_id, signal);
          const record = resolveOwnSessionRecord(sessionRepo, task.session_id, task.id);
          // Accept 'running' AND 'exited' -- exited covers Claude natural exit.
          // Queued sessions never started Claude CLI, so mark exited (not suspended)
          // to avoid a failed --resume attempt when the task is later moved back.
          if (record && record.agent_session_id
              && (record.status === 'running' || record.status === 'exited')) {
            // Capture metrics before suspend (caches are still populated)
            captureSessionMetrics(
              context.sessionManager,
              sessionRepo,
              usageHistoryRepo,
              task.session_id,
              record.id,
              record.started_at,
              record.session_type,
            );
            refineTranscriptTokens(context.sessionManager, sessionRepo, task.session_id, record.id);
            refineTranscriptToolCounts(context.sessionManager, sessionRepo, task.session_id, record.id);
            markRecordSuspended(sessionRepo, record.id, 'system');
            console.log(`[TASK_MOVE] Suspended session record ${record.id.slice(0, 8)} for task ${task.id.slice(0, 8)}`);
          } else if (record && record.status === 'queued') {
            markRecordExited(sessionRepo, record.id);
            console.log(`[TASK_MOVE] Exited queued session record ${record.id.slice(0, 8)} for task ${task.id.slice(0, 8)}`);
          }
          await context.sessionManager.suspend(task.session_id);
          tasks.update({ id: task.id, session_id: null });
        } else {
          // No active PTY -- preserve latest exited session for future resume.
          // With the state machine, canResume() checks agent_session_id existence
          // regardless of status, so this marker is mainly for UI display.
          const record = sessionRepo.getLatestForTask(task.id);
          if (record && record.agent_session_id
              && record.session_type !== 'run_script'
              && record.status === 'exited') {
            markRecordSuspended(sessionRepo, record.id, 'system');
            console.log(`[TASK_MOVE] Preserved exited session ${record.id.slice(0, 8)} for future resume`);
          }
        }
        // The task's pop-out windows and offscreen lane go with it. Here, after
        // the suspend, and not beside the archive above: a Browser pop-out
        // closing destroys its guest, and while the session still runs the lane
        // hand-off would stand a lane up for an agent about to be suspended.
        closeTaskWindows(resolvedProjectId, task.id);
        // Kill everything the task's agents left running, across every session
        // the task ever ran (a Code Review entry or a Pause suspended earlier
        // ones), before anything tries to delete the worktree. A backgrounded
        // dev server holds the directory as its cwd, which on Windows makes the
        // removal below fail and leaves a husk with no git admin entry - the
        // failure that later hangs a fresh worktree creation. After the
        // suspend, so the session has exited; before deleteTaskWorktree.
        await reapTaskLeftovers(context, resolvedProjectPath, [task]);

        // Capture git churn (fire-and-forget, best-effort). In the PR flow the
        // branch is usually already merged by the time a task reaches Done, so
        // this mostly just re-confirms whatever an earlier suspend/move already
        // captured; the no-clobber guard means a now-empty diff here can never
        // wipe that earlier real capture. Attributed to the session that just
        // ended; the task's newest record when the task had no live session.
        const churnRecord = resolveOwnSessionRecord(sessionRepo, task.session_id, task.id);
        if (churnRecord) {
          captureGitChurn(task, sessionRepo, usageHistoryRepo, churnRecord.id, resolvedProjectPath, effectiveDefaultBranch);
        }

        // Delete the local worktree to reclaim disk. Preserve branch_name and
        // session records so moving back out of Done can restore both.
        if (task.worktree_path) {
          const worktreeDeleted = await deleteTaskWorktree(context, task, tasks, resolvedProjectPath);
          if (worktreeDeleted) {
            console.log(`[TASK_MOVE] Deleted worktree for task ${task.id.slice(0, 8)} (moved to Done; branch + session preserved)`);
          } else {
            console.warn(`[TASK_MOVE] Partial worktree delete for task ${task.id.slice(0, 8)} (moved to Done; directory could not be deleted - will retry shortly, then on next startup)`);
            // A holder on its way out (a process still closing files in the
            // directory) is usually gone seconds later.
            scheduleDoneWorktreeRemovalRetry(context, resolvedProjectPath ?? null, task.id);
          }
          if (resolvedProjectPath) {
            WorktreeManager.scheduleBackgroundPrune(resolvedProjectPath);
          }
        }
        // Done ends the spawn decision `worktree_skip_reason` describes; a task
        // unarchived later re-decides at its next spawn, so a stale "project
        // folder" claim must not ride along. Outside the worktree block on
        // purpose: the task carrying a reason is the one WITHOUT a worktree.
        if (tasks.getById(task.id)) {
          tasks.setWorktreeSkipReason(task.id, null);
        }

        // Archive already happened synchronously right after tasks.move above.
        return null;
      }

      // --- Priority 2.5: TARGET HAS auto_spawn=false (and not To Do / Done, which are handled above) ---
      // → Suspend session if one exists, do NOT spawn new agent
      if (toLane && !toLane.auto_spawn) {
        context.terminalSubmitScheduler.cancel(task.id);
        // A genuine park, not a respawn: same reasoning as Priority 2's clear
        // above. Retires any label an in-flight spawn left behind so the
        // renderer's suspended-row carve-out doesn't keep it alive.
        clearSpawnProgress(context.mainWindow, task.id);
        if (task.session_id) {
          // A session that moved its own task here ends once its turn does.
          await waitIfOwnAgentSession(context, ownAgentSessionId, task.session_id, signal);
          const record = resolveOwnSessionRecord(sessionRepo, task.session_id, task.id);
          if (record && record.agent_session_id
              && (record.status === 'running' || record.status === 'exited')) {
            captureSessionMetrics(
              context.sessionManager,
              sessionRepo,
              usageHistoryRepo,
              task.session_id,
              record.id,
              record.started_at,
              record.session_type,
            );
            refineTranscriptTokens(context.sessionManager, sessionRepo, task.session_id, record.id);
            refineTranscriptToolCounts(context.sessionManager, sessionRepo, task.session_id, record.id);
            captureGitChurn(task, sessionRepo, usageHistoryRepo, record.id, resolvedProjectPath, effectiveDefaultBranch);
            markRecordSuspended(sessionRepo, record.id, 'system');
          } else if (record && record.status === 'queued') {
            markRecordExited(sessionRepo, record.id);
          }
          await context.sessionManager.suspend(task.session_id);
          tasks.update({ id: task.id, session_id: null });
          console.log(`[TASK_MOVE] Suspended session for task ${task.id.slice(0, 8)} (target column has auto_spawn=false)`);
        }
        // A non-spawning column still runs its enter rows. Only `send_message`
        // needs the agent, and `canColumnRun` already blocks that type wherever
        // "Start an agent here" is off, so nothing here can try to talk to the
        // session this branch just suspended. A notify, a script or a webhook
        // on a column the user deliberately keeps agent-free is a real and
        // legal thing to build, and it silently never fired.
        armEnterAutomations(null);
        return null;
      }

      // --- Priority 3: TASK HAS ACTIVE SESSION ---
      // Five sub-cases (in evaluation order):
      //   a) Session-track switch (isolated column entry/exit, or
      //      always_spawn_new): suspend; Phase 3 resumes-or-spawns the target
      //   b) Agent change (handoff): suspend + fall through to spawnAgent
      //   c) Same agent + model or effort change to a concrete value: suspend
      //      and respawn so --model / --effort land as launch flags (never a
      //      typed `/model` or `/effort`)
      //   d) Same agent + column message only: inject it into the running session
      //   e) Same agent + permission-only or no delta: keep session alive
      //      (no-op; a permission delta never restarts)
      if (task.session_id) {
        context.terminalSubmitScheduler.cancel(task.id);

        // The session record for the currently-live PTY. Read once here and
        // reused by the agent-change / respawn suspend paths below (one read,
        // not three).
        const activeRecord = sessionRepo.getLatestForTask(task.id);

        // --- Session switch: suspend the live session and route to Phase 2/3,
        //     which resumes-or-spawns the TARGET session via spawnAgent(toLane)
        //     (the target track + fresh-vs-resume policy are derived from the
        //     column in resolveSpawnOverrides). Two conditions trigger it:
        //       1. The live session is on a DIFFERENT track than the target wants.
        //          A single inequality covers both transitions: entering an
        //          isolated column (active != that column's id) and leaving one
        //          back to main (active is a swimlane id, target is null). The
        //          leave case is the bug guard: without it, leaving an isolated
        //          column would mis-fire as Priority 3d keep-alive and strand the
        //          isolated session in a normal column.
        //       2. The target column forces a fresh session each entry
        //          ('always_spawn_new'), even when the track is the SAME. Phase 3
        //          carries forceFresh and spawns fresh, retiring the prior pass.
        //     Suspend preserves agent_session_id so the prior record stays
        //     retireable/resumable. The worktree is shared and already exists, so
        //     Phase 2 is a no-op; going through Phase 3 reuses the CAS + abort +
        //     rollback machinery (a PTY spawned here in Phase 1 would bypass that
        //     and could leak on a mid-spawn abort). Entering with NO live session
        //     is handled by Priority 4 below; this branch only fires for a live one.
        const targetIsolatedSwimlaneId = resolveIsolatedSwimlaneId(toLane);
        const activeIsolatedSwimlaneId = activeRecord?.isolated_swimlane_id ?? null;
        const targetForceFresh = resolveForceFresh(toLane);
        const needsSessionSwitch = toLane !== undefined
          && (activeIsolatedSwimlaneId !== targetIsolatedSwimlaneId || targetForceFresh);
        if (needsSessionSwitch && toLane) {
          await suspendLiveSessionForRespawn({
            context,
            tasks,
            sessionRepo,
            usageHistoryRepo,
            taskId: task.id,
            liveSessionId: task.session_id,
            record: activeRecord,
            task,
            projectPath: resolvedProjectPath,
            defaultBaseBranch: effectiveDefaultBranch,
            phase: 'new-session',
            ownAgentSessionId,
            signal,
          });
          console.log(
            `[TASK_MOVE] Session switch for task ${task.id.slice(0, 8)}:`
            + ` ${activeIsolatedSwimlaneId ?? 'main'} -> ${targetIsolatedSwimlaneId ?? 'main'}`
            + ` (${targetForceFresh ? 'force-fresh' : 'resume-or-spawn'};`
            + ` suspended live session; Phase 3 will spawn/resume the target).`,
          );
          return {
            task,
            fromSwimlaneId,
            fromLane,
            originalPosition,
            toLane,
            skipPromptTemplate,
            resolvedProjectId,
            resolvedProjectPath,
            // Never forwarded here. A switch always lands in a different
            // conversation from the live one (another track, or a fresh
            // session), so it never saw the plan the continuation asks the
            // agent to proceed with. spawnAgent's resume check does not read
            // forceFresh, so on a force-fresh entry the continuation would
            // become a brand-new session's only prompt.
            continuationPrompt: undefined,
            suppressAutoCommand,
          };
        }

        const project = context.projectRepo.getById(resolvedProjectId);
        const { agent: effectiveTargetAgent, isHandoff: isAgentChange } = resolveTargetAgent({
          taskAgentOverride: task.agent_override,
          columnAgent: toLane?.agent_override ?? null,
          taskAgent: task.agent,
          projectDefaultAgent: project?.default_agent ?? null,
        });

        if (isAgentChange) {
          // (a) Cross-agent handoff: suspend and fall through to spawnAgent.
          // Cross-agent resume is impossible (agent_session_id is agent-specific).
          //
          // Clear per-task model/effort overrides on cross-agent handoff.
          // Override values are model-name-specific (e.g. "claude-sonnet-4-6")
          // and effort tiers are agent-specific (e.g. Claude's "xhigh" is
          // Opus-only and has no analogue on Codex). Carrying them into a
          // different agent's spawn would either crash the CLI or be silently
          // ignored. Cleanest contract: the lock applies for the duration of
          // a single agent's tenure on the task; an explicit handoff resets it
          // and the user can re-pick on the new agent if they want.
          //
          // Skipped when `task.agent_override` is set: the user locked the
          // agent at task creation and the model/effort were picked for that
          // exact agent. Normally `resolveTargetAgent` returns the override
          // and `isHandoff` is false in that case, so this branch shouldn't
          // even execute - this guard is defensive against state drift.
          await suspendLiveSessionForRespawn({
            context,
            tasks,
            sessionRepo,
            usageHistoryRepo,
            taskId: task.id,
            liveSessionId: task.session_id,
            record: activeRecord,
            task,
            projectPath: resolvedProjectPath,
            defaultBaseBranch: effectiveDefaultBranch,
            phase: 'switching-agent',
            ownAgentSessionId,
            signal,
            additionalTaskUpdates: task.agent_override
              ? undefined
              : { model_override: null, effort_override: null },
          });
          console.log(
            `[TASK_MOVE] Suspending session for task ${task.id.slice(0, 8)}`
            + ` (agent change: ${task.agent} -> ${effectiveTargetAgent}).`
            + (task.agent_override
                ? ` Kept model/effort overrides (task has locked agent_override).`
                : ` Cleared model/effort overrides.`)
            + ` Will handoff to new agent.`,
          );
          // Fall through to Phase 2/3 (handoff spawn) by not returning null.
        } else {
          // Same agent, live session. For this column transition:
          //   1. MODEL or EFFORT change to a concrete value -> suspend + `--resume`
          //      so the resumed spawn re-applies model + effort + permission as
          //      launch flags and re-delivers the column auto_command / plan-exit
          //      continuation as its prompt. Neither is ever typed into the PTY:
          //      a live `/model` left the agent paused after a Planning ->
          //      Executing handoff, and a mid-turn `/effort` cannot be confirmed.
          //   2. Column message only (no settings delta) -> inject it live.
          //   3. PERMISSION-only change, or no change -> keep the live session
          //      running untouched. A permission delta NEVER restarts: in the
          //      canonical Planning -> Executing flow the user already approved the
          //      plan in the terminal and Claude left plan mode in-session, so the
          //      recorded spawn-time permission mode is a stale signal that must
          //      not churn the PTY.
          //
          // The model/effort/auto_command delta is translated by
          // prepareInjectionPlan, so the restart policy stays in one place
          // (agent-agnostic here).
          const adapter = task.agent ? agentRegistry.get(task.agent) : undefined;
          // Resolve through the shared tier chain (task -> column) rather than
          // reading the lane directly. Reading `toLane.auto_command` alone
          // dropped a task's own auto_command on this path while the spawn path
          // honored it, so the same task behaved differently on a cold spawn
          // than on a warm move into a column with a live session.
          // The column's message now lives in its first enabled `send_message`
          // enter automation rather than in `swimlanes.auto_command`. Read
          // through the same resolver the spawn paths use, so a warm move and a
          // cold spawn cannot disagree about what the column sends.
          // A task with its automations disabled types no column message: the
          // enter group records the row as skipped with the reason instead. Its
          // own auto_command still goes out below; that is the task's input.
          const automationsRunnable = canTaskRunAutomations(
            getProjectRepos(context, resolvedProjectId).tasks.getById(task.id) ?? task,
          ).ok;
          const resolvedColumnMessage = toLane && automationsRunnable
            ? resolveColumnMessage(getProjectRepos(context, resolvedProjectId).automations.listForColumn(toLane.id))
            : null;
          // A row with a Condition or a Frequency limit rides no burst: the
          // enter group sends it after checking both.
          const columnMessage = resolvedColumnMessage && !resolvedColumnMessage.guarded ? resolvedColumnMessage : null;
          const effectiveAutoCommand = resolveEffectiveAutoCommand(task.auto_command, columnMessage?.message);
          const interpolatedAuto = effectiveAutoCommand?.trim()
            ? interpolateTaskTemplate(effectiveAutoCommand, resolveTaskTemplateVars({
                task,
                defaultBaseBranch: effectiveDefaultBranch,
                attachmentPaths: attachments.getPathsForTask(task.id),
                devPort: getDevPortForTask(task.id),
                projectPath: resolvedProjectPath,
                projectName: context.projectRepo.getById(resolvedProjectId)?.name ?? null,
                // A real move, so the move keywords resolve. The column here is
                // the DESTINATION: this is the message that column sends on
                // entry, injected into a session that is already live.
                move: toLane
                  ? { column: toLane.name, fromColumn: fromLane?.name ?? null, toColumn: toLane.name, trigger: 'enter' }
                  : null,
                workflow: readWorkflowPromptFacts(task, resolvedProjectId),
              }))
            : '';
          // Whether the burst below actually carries the COLUMN's message, as
          // opposed to the task's own pin or nothing at all. Two things read it:
          // the delivery mode, and the runner's skip list.
          const deliveredColumnMessage = columnMessage !== null
            && Boolean(interpolatedAuto)
            && effectiveAutoCommand === columnMessage.message;
          // The mode belongs to the row that supplied the message, never to
          // `swimlanes.auto_command_mode`. The automations migration resets that
          // field, so reading it here delivered every deferred column message
          // immediately on a warm move while the cold spawn honored the row's
          // own mode. A task-tier pin has no row and keeps the default.
          const injectionMode: AutoCommandMode = deliveredColumnMessage ? columnMessage.mode : 'immediate';
          // A message with line breaks cannot ride the keystroke burst, which
          // would flatten it to one line. It is pasted after the burst instead,
          // so the plan carries no message of its own. Everything else keeps
          // reading `interpolatedAuto`: the delivery mode, and the runner's skip
          // list (the row is still delivered here, not by the group).
          const trimmedAuto = interpolatedAuto.trim();
          const pastedMessage = trimmedAuto && shouldPaste(trimmedAuto) ? trimmedAuto : null;
          const plan = prepareInjectionPlan({
            adapter,
            sessionRepo,
            task,
            toLane: toLane ?? null,
            project,
            autoCommand: pastedMessage ? '' : interpolatedAuto,
            ...resolveReportedEffort(context.sessionManager, task.session_id),
          });

          // 1. Model or effort change -> suspend + respawn. Checked BEFORE live
          // injection so a settings change is never typed into the PTY. Phase 3
          // re-applies the flags and delivers the auto_command / continuation
          // via spawnAgent.
          if (plan?.restartReason) {
            await suspendLiveSessionForRespawn({
              context,
              tasks,
              sessionRepo,
              usageHistoryRepo,
              taskId: task.id,
              liveSessionId: task.session_id,
              record: activeRecord,
              task,
              projectPath: resolvedProjectPath,
              defaultBaseBranch: effectiveDefaultBranch,
              phase: restartPhaseFor(plan.restartReason),
              ownAgentSessionId,
              signal,
            });
            console.log(
              `[TASK_MOVE] Suspending session for task ${task.id.slice(0, 8)}`
              + ` (${plan.restartReason} change requires respawn). Will respawn with destination column flags.`,
            );
            return {
              task,
              fromSwimlaneId,
              fromLane,
              originalPosition,
              toLane,
              skipPromptTemplate,
              resolvedProjectId,
              resolvedProjectPath,
              continuationPrompt: options?.continuationPrompt,
              suppressAutoCommand,
            };
          }

          // 2. No settings delta, but a column message (or the task's own
          // auto_command) -> deliver it to the running PTY: a one-line message as
          // the burst's one command, a multi-line one pasted after it. A pasted
          // message takes this branch with or without a plan: with none it would
          // fall to 3, which arms the group with nothing delivered and sends the
          // row again.
          if (plan || pastedMessage) {
            const injectedSessionId = task.session_id;
            const reportOutcome = (report: InjectionReport): void =>
              reportAutoCommandOutcome(context, tasks, task, report, resolvedProjectId);
            if (plan && plan.sequence.length > 0) {
              context.terminalSubmitScheduler.scheduleKeystrokes(task.id, injectedSessionId, plan.sequence, {
                verifier: plan.verifier,
                mode: injectionMode,
                // Rung 3 of the delivery ladder. Routed through the allowlisted
                // in-place restart rather than a new spawn call, so this adds no
                // spawn entry point (see spawn-entry-point-parity.md).
                escalate: async (commands) => {
                  if (!resolvedProjectPath) return false;
                  // `restartSessionForSettingsChange` mutates per-task session
                  // state and documents that its caller must hold the task lock.
                  // Taking it here is safe and not reentrant: `scheduleKeystrokes`
                  // is fire-and-forget, so this callback runs well after the
                  // TASK_MOVE handler released the lock.
                  return withTaskLock(task.id, async () => {
                    const restarted = await restartSessionForSettingsChange(
                      context,
                      resolvedProjectId,
                      resolvedProjectPath,
                      task.id,
                      { phase: 'resending-command', resumePrompt: commands.join('\n') },
                    );
                    return restarted.ok;
                  });
                },
                onOutcome: reportOutcome,
              });
            }
            // After the burst, never racing it: the paste waits for the turn to
            // end and for the scheduler to finish this task's keystrokes. A move
            // out of the column cancels it (`supersedeMessageDeliveries`).
            if (pastedMessage) {
              pasteAgentMessageInBackground(context, {
                taskId: task.id,
                sessionId: injectedSessionId,
                message: pastedMessage,
                onOutcome: reportOutcome,
              });
            }
            const injectedTexts = (plan?.sequence ?? []).map((command) => command.text);
            console.log(
              `[TASK_MOVE] Injecting ${injectedTexts.length} command(s) for task ${task.id.slice(0, 8)}`
              + ` into running session${plan?.verifier ? ' (with command verification)' : ''}: `
              + `${injectedTexts.join(' | ')}`
              + (pastedMessage ? `${injectedTexts.length > 0 ? ', then ' : ''}a ${pastedMessage.length}-character message to paste` : ''),
            );
            // Name the row the burst above actually carried, so it is not sent
            // a second time, and let the rest of the group run after the lock.
            // `deliveredColumnMessage` is `resolveEffectiveAutoCommand`'s own
            // answer read back rather than re-derived: a task's MCP-set
            // `auto_command` outranks the column, and in that case the column's
            // row has NOT been delivered and must still run.
            armEnterAutomations(deliveredColumnMessage ? columnMessage.id : null);
            return null;
          }

          // 3. Permission-only delta, or no delta -> keep the live session alive.
          // A permission change never restarts (see header); there is no
          // model/effort delta to apply and no column message to deliver.
          console.log(
            `[TASK_MOVE] Task ${task.id.slice(0, 8)} keeping active session alive`
            + ` (no model/effort change; permission-only or no delta, same agent).`,
          );
          // Nothing was injected on this branch, so nothing is pre-delivered:
          // the whole enter group runs, message row included.
          armEnterAutomations(null);
          return null;
        }
      }

      // --- Priority 4 (or 3a fall-through): TASK HAS NO ACTIVE SESSION ---
      // Return the plan; Phase 2 creates the worktree (unlocked, serialized
      // per-project by WorktreeManager.projectQueues), Phase 3 spawns.

      // Symmetric clear for cross-agent destinations on the no-session path.
      // Mirrors the live-handoff clear in Priority 3a (line ~336): model and
      // effort overrides are model-name-specific and don't carry across
      // agents. Without this, a task created in a Claude column with overrides
      // and dragged into a Codex column before its first spawn would pass
      // `claude-sonnet-4-6` into Codex's command builder. We do this here
      // (after the early returns above) so non-spawning destinations (Done,
      // auto_spawn=false) keep the user's overrides intact for when the task
      // moves back into a spawning column.
      //
      // Skipped when `task.agent_override` is set: the user locked the agent
      // at task creation, so the model/effort were picked for that exact
      // agent. Column moves cannot trigger an agent change in this case
      // (resolveTargetAgent returns task.agent_override regardless of column),
      // so the overrides remain valid.
      let planTask = task;
      if (!planTask.agent_override && (planTask.model_override || planTask.effort_override) && toLane) {
        const project = context.projectRepo.getById(resolvedProjectId);
        const projectDefault = project?.default_agent ?? null;
        const sourceAgent = planTask.agent ?? projectDefault;
        const targetAgent = toLane.agent_override ?? projectDefault;
        if (sourceAgent && targetAgent && sourceAgent !== targetAgent) {
          tasks.update({
            id: planTask.id,
            model_override: null,
            effort_override: null,
          });
          console.log(
            `[TASK_MOVE] Cleared model/effort overrides on task ${planTask.id.slice(0, 8)}`
            + ` (cross-agent move ${sourceAgent} -> ${targetAgent}, no live session).`,
          );
          // Refresh the snapshot so the downstream plan reflects the cleared
          // state (Phase 3 re-reads task from DB anyway, but the plan object
          // is a captured snapshot consumed by the caller).
          const refreshed = tasks.getById(planTask.id);
          if (refreshed) planTask = refreshed;
        }
      }

      // A paused agent stays paused through any move: only the user's Resume
      // starts it (`spawnAgent` refuses it too). The column's other enter rows
      // still run, as they do on any entry, and the rows that need the agent
      // run at a Resume in this column (`resumeTaskSession`). The same shape as
      // Priority 2.5: no worktree work, no spawn. Below the cross-agent clear,
      // because that Resume starts this column's agent. A recovery move out of
      // Done keeps the plan instead: Done removed the worktree, so the move
      // restores it and `spawnAgent` starts nothing, as an unarchive does.
      if (toLane && !suppressAutoCommand && isHeldPause(sessionRepo.getLatestForTask(task.id))) {
        clearSpawnProgress(context.mainWindow, task.id);
        console.log(`[TASK_MOVE] Task ${task.id.slice(0, 8)} stays paused in ${toLane.name} until the user resumes it`);
        armEnterAutomations(null, true);
        return null;
      }

      return {
        task: planTask,
        fromSwimlaneId,
        fromLane,
        originalPosition,
        toLane,
        skipPromptTemplate,
        resolvedProjectId,
        resolvedProjectPath,
        continuationPrompt: options?.continuationPrompt,
        suppressAutoCommand,
      };
    }).finally(() => {
      releaseOwnMoveMark?.();
      releaseOwnMoveMark = null;
    });

    if (!plan) {
      // Phase 1 fully handled the move. The destination's enter rows run HERE,
      // after the lock, so a five-minute `run_script` row does not hold that
      // task's lock for five minutes. Skipped on shutdown for the same reason
      // Phase 2 is: the DB is closing.
      if (runEnterAutomations && !isShuttingDown()) await runEnterAutomations();
      return;
    }

    const { task, fromSwimlaneId, fromLane, originalPosition, toLane, skipPromptTemplate, resolvedProjectId, resolvedProjectPath, continuationPrompt, suppressAutoCommand } = plan;

    // Shutdown started while Phase 1 ran. Skip Phase 2 git work and Phase 3
    // spawn so we don't write to a closed DB. autoSpawnTasks on next launch
    // will spawn for the destination column. A respawn branch (model or effort
    // change, agent handoff, session switch) may have already emitted
    // a spawn-progress label before this point (see suspendLiveSessionForRespawn);
    // this return sits outside every try/finally below, so it must retire that
    // label itself or it strands until the 120s TTL.
    if (isShuttingDown()) {
      clearSpawnProgress(context.mainWindow, task.id);
      return;
    }

    // === Phase 2 (unlocked, slow) ===
    // All async operations below receive the abort signal so a newer move
    // cancels them via AbortError. Cleanup is centralized in the outer catch.
    // Git I/O is serialized per-project by WorktreeManager.projectQueues; DB
    // writes inside ensureTaskWorktree are sync better-sqlite3 calls.
    const onProgress = createProgressCallback(context.mainWindow, task.id);
    // Emitted only when the git op parks in the per-project queue behind
    // another op. The 'fetching' label is emitted by the git layer itself once
    // the op actually starts, so we no longer eagerly show "Fetching latest..."
    // here (which made a queue wait masquerade as an active fetch).
    const onWaitProgress = (info: GitWaitProgress) => emitSpawnWaiting(
      context.mainWindow,
      task.id,
      info.jobsAhead,
      info.runningLabel ? { label: info.runningLabel, elapsedMs: info.runningElapsedMs } : undefined,
    );
    // The agent started while a new worktree ran its setup script
    // (`createEarlyAgentLauncher`), for Phase 3's spawn to adopt. Discarded
    // after Phase 3 and in the catch, so a path that never reaches the spawn
    // leaves no agent behind (a no-op once adopted).
    // Typed by assertion: assigned inside a nested try, which control flow
    // analysis does not carry into the catch below.
    let earlyAgent = null as EarlyAgentHandle | null;
    // The note Phase 3's prompt carries when the script runs on in the background.
    let setupStillRunning: string | undefined;
    try {
      // Create worktree if worktrees are enabled and task doesn't have one yet.
      // If worktree creation fails (e.g. duplicate branch), revert the task
      // back to its original column so it doesn't get stuck without a session.
      try {
        const {
          tasks: tasksPhase2, automations: automationsPhase2, automationRuns: automationRunsPhase2, attachments: attachmentsPhase2,
        } = getProjectRepos(context, resolvedProjectId);
        // Only a spawning move gets an early agent; a move with no destination
        // lane (and every caller but this one and auto-spawn) runs the script
        // before the agent, as before.
        const initScriptMode = toLane
          ? resolveInitScriptMode(context, resolvedProjectPath, createEarlyAgentLauncher({
            context,
            tasks: tasksPhase2,
            automations: automationsPhase2,
            automationRuns: automationRunsPhase2,
            attachments: attachmentsPhase2,
            taskId: task.id,
            toLane,
            settingsSourceLane: fromLane ?? null,
            projectId: resolvedProjectId,
            projectPath: resolvedProjectPath,
            signal,
          }))
          : undefined;
        const hadWorktree = Boolean(task.worktree_path);
        earlyAgent = await ensureTaskWorktree(context, task, tasksPhase2, resolvedProjectPath, {
          signal, onProgress, onWaitProgress, projectId: resolvedProjectId, initScript: initScriptMode,
        });
        setupStillRunning = setupStillRunningFor(context, resolvedProjectPath, initScriptMode, hadWorktree ? null : task.worktree_path);
      } catch (error) {
        // Let AbortError propagate to the outer catch for centralized handling
        if (isAbortError(error)) throw error;

        // Best-effort cleanup of stale resources that may have caused the failure
        // (e.g. leftover directory or branch from a previous partial cleanup).
        // This makes the next drag attempt succeed without requiring an app restart.
        if (resolvedProjectPath) {
          try {
            const worktreeManager = new WorktreeManager(resolvedProjectPath);
            // Creation just failed, possibly before the DB write landed, so no
            // single field is trustworthy here. Probe every directory this task
            // could plausibly own: the stored path, the folder it is pinned to,
            // the numeric name a fresh creation would pick, and the legacy
            // title-derived name from before the numeric scheme.
            const candidateWorktreePaths = candidateWorktreePathsFor(task, resolvedProjectPath);
            // The BRANCH is derived independently of the folder. Folders are
            // numeric now, so falling back to the folder name here would try to
            // delete a branch literally called "460".
            const expectedBranch = task.branch_name || legacyAutoBranchNameFor(task);
            // Only an AUTO-GENERATED branch may be force-deleted here. This block
            // exists to clear leftovers from a partial cleanup, but `removeBranch`
            // is `git branch -D` with every error swallowed - so for a custom,
            // agent-supplied name it silently destroys the branch and its commits
            // on ANY worktree failure, whenever that branch is not checked out
            // somewhere. Task #538 would have lost commit 4261ff1e that way, and
            // the branch was never pushed, so origin would not have saved it.
            //
            // It was latent only because git refuses to delete a checked-out
            // branch - the very condition that caused #538 - and the main
            // checkout has since moved off it.
            //
            // `legacyAutoBranchNameFor` (the null case) is auto-generated by
            // construction, so the intended cleanup is preserved either way.
            const branchIsDeletable = !task.branch_name
              || isAutoGeneratedBranch(task.branch_name, task.id, task.title);

            await worktreeManager.withLock(async () => {
              // A newer creation for this task (a superseding move's) holds one
              // of these paths, and its setup script runs outside the git queue.
              // This failed creation's own hold ended before this job was queued,
              // so any hold here is the newer one's, and the directory and branch
              // are its. Leave all of it alone. A creation that starts after this
              // check queues its git phase behind this job.
              const inFlightPath = candidateWorktreePaths.find(isWorktreeCreationInFlight);
              if (inFlightPath) {
                console.log(`[TASK_MOVE] Skipped stale cleanup for task ${task.id.slice(0, 8)}: a newer creation holds ${inFlightPath}`);
                return;
              }
              for (const expectedPath of candidateWorktreePaths) {
                if (!fs.existsSync(expectedPath)) continue;
                // Per candidate, because removeWorktree THROWS for a path
                // outside this project's worktrees root (the raw stored
                // worktree_path is one candidate, and it is probed first). A
                // throw that escaped this loop would skip the remaining
                // candidates AND the prune / removeBranch below, leaving exactly
                // the stale state this block exists to clear.
                try {
                  // `moderate`, not the default `thorough`. Creation just failed
                  // on this same path, so a second full-budget grind re-proves
                  // what we already know while the user waits and the git queue
                  // stays held: measured, the two thorough passes put the
                  // failure toast ~62s out instead of ~34s. This block is
                  // explicitly best-effort ("will retry on next attempt"), and a
                  // still-pinned path is picked up by the husk-reuse and
                  // startup-retry net either way.
                  await worktreeManager.removeWorktree(expectedPath, { removalProfile: 'moderate' });
                } catch (removalError) {
                  console.warn(`[TASK_MOVE] Skipped stale worktree candidate ${expectedPath}:`, removalError);
                  continue;
                }
                // A removal that merely FAILS returns false rather than throwing,
                // so verify on disk.
                if (fs.existsSync(expectedPath)) {
                  console.warn(`[TASK_MOVE] Could not remove stale worktree directory (file handles may still be held): ${expectedPath}`);
                } else {
                  console.log(`[TASK_MOVE] Cleaned stale worktree directory: ${expectedPath}`);
                }
              }
              await worktreeManager.pruneWorktrees();
              if (branchIsDeletable) {
                await worktreeManager.removeBranch(expectedBranch);
              } else {
                console.log(`[TASK_MOVE] Kept custom branch "${expectedBranch}" (cleanup only removes auto-generated branches)`);
              }
            }, { label: `stale-cleanup:${task.id.slice(0, 8)}` });
          } catch (cleanupError) {
            console.warn('[TASK_MOVE] Stale resource cleanup failed (will retry on next attempt):', cleanupError);
          }
        }

        // Revert + session cleanup is handled by the outer catch below, which
        // runs on every non-abort failure (worktree setup, branch checkout,
        // or spawn). Wrap the error with a context message so the toast
        // surfaced to the renderer distinguishes worktree failures from
        // later spawn failures.
        const message = error instanceof Error ? error.message : String(error);
        throw new Error(`Worktree setup failed: ${message}`, { cause: error });
      }

      // Checkout the task's branch in the main repo (non-worktree tasks only).
      // Intentionally unguarded: if checkout fails, the error propagates to
      // the outer catch which also handles AbortError cleanup. That includes
      // BranchCheckoutBlockedError, which reaches the user as a toast here, so
      // this is the one call site that needs no notifySpawnBlocked.
      await ensureTaskBranchCheckout(context, task, resolvedProjectPath, { signal, onProgress, onWaitProgress, projectId: resolvedProjectId });

      // === Phase 3 (locked, short) ===
      // CAS-check invariants before spawning. If a newer move ran during our
      // Phase 2 gap, task.swimlane_id / session_id will have changed and we
      // should bail out to avoid spawning for a stale target column. The
      // try/finally guarantees spawn-progress is cleared whether we spawn,
      // bail on CAS mismatch, or throw. The session-changed event would also
      // clear it via upsertSession, but fast-starting agents (Codex) race
      // with the renderer's state updates.
      await withTaskLock(input.taskId, async () => {
        try {
          // Shutdown started while we were waiting for the lock or Phase 2 ran.
          // The DB may already be closed; skip the spawn entirely. The
          // try/finally still calls clearSpawnProgress to clean the renderer UI.
          if (isShuttingDown()) return;
          signal.throwIfAborted();
          const { tasks: tasksPhase3, automations: automationsPhase3, automationRuns: automationRunsPhase3, attachments: attachmentsPhase3 } = getProjectRepos(context, resolvedProjectId);
          const current = tasksPhase3.getById(task.id);
          if (!current) {
            console.log(`[TASK_MOVE] Task ${task.id.slice(0, 8)} was deleted during Phase 2 - skipping spawn`);
            return;
          }
          if (current.swimlane_id !== input.targetSwimlaneId) {
            console.log(`[TASK_MOVE] Task ${task.id.slice(0, 8)} moved to a different column during Phase 2 - skipping spawn`);
            return;
          }
          // Phase 1 found no session, so another path started an agent for the
          // task while this move made its worktree. That agent did not get this
          // move's prompt and may not run in the worktree. A warning, so it
          // reaches the log even with info lines off (see
          // docs/architecture/sessions/crash-recovery.md, step 8).
          if (current.session_id) {
            console.warn(
              `[TASK_MOVE] Task ${task.id.slice(0, 8)} already has session ${current.session_id.slice(0, 8)},`
              + ' started by another path while this move made its worktree - skipping spawn',
            );
            return;
          }
          // A move no person made passed the lock while its workflow ran (an
          // engine start, a step move, a Move to column row, a plan exit), and
          // the workflow was paused while this move made its worktree. A paused
          // workflow starts nothing: the card stays where the move put it, and
          // Resume brings its agent back there.
          if (ranUnderRunningWorkflow && isTaskWorkflowPaused(current, resolvedProjectId)) {
            console.log(`[TASK_MOVE] Task ${task.id.slice(0, 8)}: its workflow was paused during Phase 2 - skipping spawn`);
            return;
          }

          // Execute transition actions + ensure agent is running (handles resume/spawn/auto_command)
          emitSpawnProgress(context.mainWindow, task.id, 'starting-agent');
          const dbPhase3 = getProjectDb(resolvedProjectId);
          const sessionRepoPhase3 = new SessionRepository(dbPhase3);
          const engine = createTransitionEngine(context, automationsPhase3, automationRunsPhase3, tasksPhase3, sessionRepoPhase3, attachmentsPhase3, resolvedProjectId, resolvedProjectPath);
          if (toLane) {
            await spawnAgent({
              context, engine, tasks: tasksPhase3, sessionRepo: sessionRepoPhase3, task: current, fromSwimlaneId, toLane, skipPromptTemplate, signal,
              projectId: resolvedProjectId, projectPath: resolvedProjectPath, continuationPrompt, suppressAutoCommand,
              settingsSourceLane: fromLane ?? null, attachments: attachmentsPhase3, moveCarriesMessage: options?.carriesMessage === true,
              earlyAgent: earlyAgent ?? undefined, setupStillRunning,
            });
          }
        } finally {
          clearSpawnProgress(context.mainWindow, task.id);
        }
      });
      // Phase 3 returned without a spawn adopting it (a check above failed).
      await earlyAgent?.discard();
    } catch (error) {
      // clearSpawnProgress touches only in-memory maps and a guarded IPC
      // send, never the DB, so it is safe to call unconditionally here -
      // ahead of the shutdown bail below - rather than risk stranding a
      // respawn branch's label (see suspendLiveSessionForRespawn) until the
      // 120s TTL.
      clearSpawnProgress(context.mainWindow, task.id);
      // An early agent nothing adopted goes before the rollback below; one the
      // spawn adopted is the task's session, which the rollback handles.
      await earlyAgent?.discard();

      // Shutdown closed the DB while a Phase 1 / 2 / 3 await was in flight.
      // Both the post-await DB write inside Phase 1 (e.g. line 226's
      // tasks.update after sessionManager.suspend) and the rollback below
      // would throw against the closed connection. Bail silently - shutdown
      // is already clearing session_id on running sessions and Phase 1's
      // earlier sync writes (tasks.move, tasks.archive, markRecordSuspended)
      // are committed. The IPC wrapper's swallow is a backstop; this guard
      // also keeps the rollback's "Rollback after move failure failed" log
      // from firing during shutdown.
      if (isShuttingDown()) return;

      const abort = isAbortError(error);

      // Unified rollback path for Phase 2/3 failures: clean up any partially
      // spawned session and revert the task move if the task is still in the
      // destination column. The CAS guard on swimlane_id means a concurrent
      // move that already relocated the task (e.g. user dragged again) keeps
      // its authoritative state - we only undo our own forward move.
      await withTaskLock(input.taskId, async () => {
        try {
          context.sessionManager.removeByTaskId(task.id);
          const { tasks: tasksRollback } = getProjectRepos(context, resolvedProjectId);
          const current = tasksRollback.getById(task.id);
          if (!current) return;
          if (current.session_id) {
            tasksRollback.update({ id: task.id, session_id: null });
          }
          if (!abort && current.swimlane_id === input.targetSwimlaneId) {
            tasksRollback.move({
              taskId: input.taskId,
              targetSwimlaneId: fromSwimlaneId,
              targetPosition: originalPosition,
            }, { origin: 'rollback', reason: 'The move into the column failed.' });
          }
        } catch (rollbackError) {
          console.error('[TASK_MOVE] Rollback after move failure failed:', rollbackError);
        }
      });

      if (abort) {
        console.log(`[TASK_MOVE] Aborted stale move for task ${task.id.slice(0, 8)}`);
        return;
      }
      throw error;
    }
  } finally {
    // Clean up controller if this is still the active one for this task
    releaseMoveController(input.taskId, moveController);
  }
  };

  let moveSucceeded = false;
  try {
    await (logProjectName ? runWithProjectLogContext(logProjectName, runMove) : runMove());
    moveSucceeded = true;
  } finally {
    // Announce iff the DB write committed - NOT merely "iff the move succeeded".
    //
    // A failed move can still leave a committed change. The rollback skips the
    // revert entirely on the abort path (`!abort &&` in its guard), skips it
    // again when its CAS sees a concurrent move already relocated the task, and
    // is itself best-effort inside its own try/catch. Announcing only on the
    // success path would therefore reproduce the exact bug this whole change
    // exists to fix: a real board change that nobody is told about.
    //
    // Erring toward announcing is cheap. A redundant push coalesces into the
    // renderer's 250ms debounced board reload, the Monitor debounces too, and
    // phones already tolerate duplicate board events (the session-lifecycle
    // feed deliberately double-emits). A missing one is the bug.
    //
    // A `finally` does not swallow the rethrow, and the shutdown gate is
    // load-bearing rather than defensive: on that path the DB is already closed
    // and the window is going away, but sendToRenderer would still record a push.
    if (moveCommitted && announceProjectId && !isShuttingDown()) {
      // Every origin, including `renderer`. The subscribers here (paired phones
      // via the mobile bridge, and the Agent Monitor) are external to whoever
      // made the move, so a desktop drag has to reach them just as an agent's
      // move does. Sent as 'task-updated' rather than a new 'task-moved' kind
      // because read-board forwards `change` straight onto the wire, making a
      // new member a phone-visible protocol change for no gain.
      //
      // This is the SECOND bus emit for the move (the first fired at the commit
      // point inside Phase 1). It is not redundant: this one runs after the
      // rollback, so it is what tells a phone that a committed-then-failed
      // move went back. The renderer push here is the origin's own: the commit
      // point sent a quiet reload, and the `agent` and `auto-move` toasts fire
      // here only, once per move.
      //
      // The push is wrapped because this runs in a `finally`: a throwing
      // sendToRenderer would REPLACE whatever error runMove was already
      // propagating (the rollback tests assert the original surfaces) or turn
      // a clean move into a rejection. The bus emit fences itself the same way.
      emitBoardChanged();
      try {
        MOVE_PUSH_BY_ORIGIN[origin]?.(context, announceProjectId, input, movedTaskTitle);
      } catch (announceError) {
        console.error(`[TASK_MOVE] Announce failed for task ${input.taskId.slice(0, 8)}:`, announceError);
      }

      // PR linking is deliberately SUCCESS-only, unlike the two announcements
      // above. It used to live at the call sites, where it ran only once
      // `await handleTaskMove` had resolved, so the TIMING is unchanged; folding
      // it into the committed-but-failed case would newly fire gh queries for
      // moves that blew up after writing. Gated on a branch + non-To Do lane
      // inside the helper, and fire-and-forget so a slow query never blocks.
      //
      // The COVERAGE is not unchanged, and that is the one deliberate behavior
      // change in this block: only the renderer and plan-exit call sites ever
      // called this, so an agent's `move_task` and a phone's move never linked
      // a PR for the lane they landed in. Both do now, which means both can
      // spawn a `gh` query they previously did not. The helper's own lane and
      // anchor gates plus `linkPR`'s 60s per-task throttle are what keep a
      // scripted loop of agent moves from turning into a subprocess per move.
      if (moveSucceeded) {
        autoLinkPRForTask(context, input.taskId, announceProjectId);
      }
    }
  }
}

export function registerTaskMoveHandlers(context: IpcContext): void {
  ipcMain.handle(IPC.TASK_MOVE, async (event, input, projectId?: string | null) => {
    // Prefer the renderer-stamped projectId (captured at drop time) over the
    // ambient current project, which can change if the user switches projects
    // during the FlyingCard flight. Resolve the matching projectPath too so
    // Phase 2/3 worktree + spawn work also targets the right project, not the
    // ambient one. handleTaskMove keeps the ambient fallback for main-process
    // internal callers that pass undefined.
    let resolvedProjectId: string | null = null;
    try {
      const resolved = resolveProjectContext(context, projectId);
      resolvedProjectId = resolved.projectId;
      // 'renderer': the board already moved the card optimistically, so this is
      // the one origin that sends no origin push. It still reaches paired phones
      // and the Monitor via the unconditional board-changed emit inside the
      // handler. A move from another window (the detached Agent Monitor) reaches
      // the main window's board at its commit point, before a Done move's
      // teardown, and again through the `finally` below.
      return await handleTaskMove(context, input, 'renderer', resolved.projectId, resolved.projectPath, {
        onCommitted: () => announceToMainWindow(context, event, resolved.projectId),
      });
    } catch (error) {
      // Shutdown closes the DB synchronously; any handler that crossed an
      // await boundary will throw "database connection is not open" or an
      // AbortError when it resumes. Swallow these to keep the shutdown log
      // clean - the user already quit and Phase 1's DB writes are committed.
      if (isShuttingDown()) return;
      throw error;
    } finally {
      // Settled, not succeeded: a move can commit and then fail, which still
      // changed the board (the announce block in handleTaskMove explains why).
      // The helper itself stays quiet during shutdown. It gets no bus change,
      // because handleTaskMove announced at the commit point and again at settle.
      announceTaskWrite(context, event, resolvedProjectId, null);
    }
  });

  // Queryable snapshot of in-flight spawn-progress labels (keyed by taskId).
  // syncSessions() reconciles its spawnProgress map against this so an HMR
  // reload during the brief "Starting agent..." window cannot strand a card.
  ipcMain.handle(IPC.TASK_GET_SPAWN_PROGRESS, () => getInFlightSpawnProgress());

  // Drain a project's queued expired-conversation notices, minus any whose task
  // was deleted or archived while it waited. Synchronous, so two takes that
  // race (the push's and a project switch's) split the queue and never both get
  // the same notice. See pending-conversation-expired.ts.
  ipcMain.handle(IPC.TASK_TAKE_CONVERSATION_EXPIRED, (_event, projectId: unknown) => {
    if (typeof projectId !== 'string') return [];
    const notices = takeConversationExpired(projectId);
    if (notices.length === 0) return notices;
    return keepNoticesForLiveTasks(notices, () => getProjectRepos(context, projectId).tasks);
  });
}
