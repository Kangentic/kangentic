describe('Command Builder Logic', () => {
  it('quoteArg skips quoting simple paths', () => {
    expect(quoteArg('claude')).toBe('claude');
    expect(quoteArg('C:/Users/dev/.local/bin/claude')).toBe('C:/Users/dev/.local/bin/claude');

    const backslashPath = 'C:\\Users\\dev\\.local\\bin\\claude.EXE';
    const quotedBackslash = quoteArg(backslashPath);
    // Backslashes need quoting; quote character depends on platform (" on Windows, ' on POSIX)
    expect(quotedBackslash).toMatch(/^["'].*["']$/);

    const pathWithSpaces = 'C:/Program Files/claude/claude.exe';
    const quoted = quoteArg(pathWithSpaces);
    expect(quoted).toMatch(/^["'].*["']$/);
  });

  it('quoteArg sanitises multiline input by default (regression guard)', () => {
    const multiline = 'line1\nline2\nline3';
    const result = quoteArg(multiline);
    expect(result).not.toContain('\n');
    expect(result).toContain('line1 line2 line3');
  });

  it('quoteArg with multiline: true preserves newlines under bash', () => {
    const xml = '<task>\n  <title>Test</title>\n</task>';
    const result = quoteArg(xml, 'bash', { multiline: true });
    expect(result).toContain('\n  <title>Test</title>\n');
    expect(result.startsWith("'<task>")).toBe(true);
    expect(result.endsWith("</task>'")).toBe(true);
  });

  it('quoteArg with multiline: true converts newlines to PowerShell `n escape', () => {
    // PowerShell continuation via PTY is unreliable - pin the input to one
    // physical line and let PowerShell's escape parser produce the newlines.
    const xml = '<task>\n  <title>Test</title>\n</task>';
    const result = quoteArg(xml, 'pwsh', { multiline: true });
    // Final string is one physical line (no embedded newlines)
    expect(result).not.toContain('\n');
    // Newlines are encoded as the PowerShell escape `n
    expect(result).toBe('"<task>`n  <title>Test</title>`n</task>"');
  });

  it('quoteArg with multiline: true escapes tabs as PowerShell `t', () => {
    const result = quoteArg('col1\tcol2', 'powershell', { multiline: true });
    expect(result).not.toContain('\t');
    expect(result).toBe('"col1`tcol2"');
  });

  it('quoteArg with multiline: true preserves literal backticks via doubling under PowerShell', () => {
    // A literal backtick in the prompt content must NOT collide with the
    // newline escape we add - existing backticks get doubled first.
    const result = quoteArg('use `code` here\nline2', 'pwsh', { multiline: true });
    // ``code`` keeps the literal backticks; `n is the newline escape we add
    expect(result).toBe('"use ``code`` here`nline2"');
  });

  it('quoteArg with multiline: true falls back to sanitisation under cmd', () => {
    // cmd.exe terminates the command on a literal newline mid-quote, so we
    // accept readability loss to keep the command parseable.
    const xml = '<task>\n  <title>Test</title>\n</task>';
    const result = quoteArg(xml, 'cmd', { multiline: true });
    expect(result).not.toContain('\n');
    expect(result).toContain('<task>');
    expect(result).toContain('<title>Test</title>');
  });

  it('quoteArg with multiline: true falls back to sanitisation when shell is omitted', () => {
    // Without a shell hint we can't tell PowerShell from cmd, and only the
    // unix branch tolerates raw newlines. Conservative fallback: sanitise.
    const xml = '<task>\n  <title>Test</title>\n</task>';
    const result = quoteArg(xml, undefined, { multiline: true });
    expect(result).not.toContain('\n');
    expect(result).toContain('<task>');
    expect(result).toContain('<title>Test</title>');
  });

  it('isCmdShell matches cmd basename only, not random paths containing "cmd"', () => {
    // Anchored basename match so unrelated paths don't trigger the cmd
    // fallback in quoteArg.
    expect(isCmdShell('cmd')).toBe(true);
    expect(isCmdShell('cmd.exe')).toBe(true);
    expect(isCmdShell('CMD.EXE')).toBe(true);
    expect(isCmdShell('C:\\Windows\\System32\\cmd.exe')).toBe(true);
    expect(isCmdShell('/c/windows/system32/cmd.exe')).toBe(true);

    expect(isCmdShell('/usr/local/cmd-tool/sh')).toBe(false);
    expect(isCmdShell('command.com')).toBe(false);
    expect(isCmdShell('bash')).toBe(false);
    expect(isCmdShell('powershell')).toBe(false);
    expect(isCmdShell('pwsh')).toBe(false);
  });

  it('PowerShell call operator prefix', () => {
    function prefixForShell(command: string, shellName: string): string {
      if (shellName.includes('powershell') || shellName.includes('pwsh')) {
        return '& ' + command;
      }
      return command;
    }

    const cmd = '"C:\\Users\\dev\\.local\\bin\\claude.EXE" --dangerously-skip-permissions';

    expect(prefixForShell(cmd, 'powershell')).toBe('& ' + cmd);
    expect(prefixForShell(cmd, 'pwsh')).toBe('& ' + cmd);
    expect(prefixForShell(cmd, 'C:\\Windows\\System32\\WindowsPowerShell\\v1.0\\powershell.exe')).toBe('& ' + cmd);

    expect(prefixForShell(cmd, 'bash')).toBe(cmd);
    expect(prefixForShell(cmd, 'cmd')).toBe(cmd);
    expect(prefixForShell(cmd, '/bin/zsh')).toBe(cmd);
  });

  it('interpolateTemplate replaces variables', () => {
    const template = '{{title}}{{description}}';
    const vars = { title: 'My Task', description: ': Build the feature' };
    const result = interpolateTemplate(template, vars);

    expect(result).toBe('My Task: Build the feature');
  });

  it('interpolateTemplate with empty description omits separator', () => {
    const template = '{{title}}{{description}}';
    const vars = { title: 'My Task', description: '' };
    const result = interpolateTemplate(template, vars);

    expect(result).toBe('My Task');
  });

  it('interpolateTemplate handles missing variables', () => {
    const template = '{{title}} in {{worktreePath}}';
    const vars = { title: 'Fix bug', worktreePath: '' };
    const result = interpolateTemplate(template, vars);

    expect(result).toBe('Fix bug in ');
  });

  it('quoteArg uses single quotes when shell is bash (prevents $var expansion)', () => {
    const result = quoteArg('fix $count bug', 'bash');
    expect(result).toBe("'fix $count bug'");
  });

  it('quoteArg uses single quotes when shell is WSL', () => {
    const result = quoteArg('deploy to $HOME/app', 'wsl -d Ubuntu');
    expect(result).toBe("'deploy to $HOME/app'");
  });

  it('quoteArg uses double quotes when shell is PowerShell', () => {
    const result = quoteArg('fix the bug', 'powershell');
    expect(result).toBe('"fix the bug"');
  });

  it('quoteArg uses double quotes when shell is cmd', () => {
    const result = quoteArg('fix the bug', 'cmd');
    expect(result).toBe('"fix the bug"');
  });

  it('quoteArg escapes single quotes inside single-quoted strings for bash', () => {
    const result = quoteArg("it's a bug", 'bash');
    expect(result).toBe("'it'\\''s a bug'");
  });

  it('quoteArg preserves backtick commands in single-quoted mode', () => {
    const result = quoteArg('check `whoami` output', '/usr/bin/bash');
    expect(result).toBe("'check `whoami` output'");
  });

  it('quoteArg escapes backticks for PowerShell', () => {
    const result = quoteArg('use `code` block', 'powershell');
    // Each backtick should be doubled for PowerShell (` → ``)
    expect(result).toBe('"use ``code`` block"');
  });

  it('quoteArg escapes $ for PowerShell to prevent variable expansion', () => {
    const result = quoteArg('fix $HOME and $(whoami) issue', 'powershell');
    // $ should be escaped as `$ for PowerShell
    expect(result).toContain('`$HOME');
    expect(result).toContain('`$(whoami)');
    // Should not contain unescaped $ (every $ should be preceded by `)
    expect(result).not.toMatch(/[^`]\$|^"\$/);
  });

  it('quoteArg escapes both backticks and $ in PowerShell prompt with code blocks', () => {
    const prompt = 'Refactor: ```typescript\nconst $count = items.length;\n```';
    const result = quoteArg(prompt, 'pwsh');
    // Backticks doubled, $ escaped - should not hang PowerShell
    expect(result).toContain('````');
    expect(result).toContain('`$count');
  });

  it('quoteArg leaves $ and backticks literal in bash single quotes', () => {
    const result = quoteArg('use $HOME and `whoami`', 'bash');
    // Single quotes protect everything - no escaping needed
    expect(result).toBe("'use $HOME and `whoami`'");
  });

  it('quoteArg with shell omitted falls back to platform detection', () => {
    const result = quoteArg('hello world');
    // Should produce either single or double quotes depending on platform
    expect(result).toMatch(/^["']hello world["']$/);
  });

  it('full pipeline: interpolateTemplate + quoteArg with multiline description (pre-cleaned)', () => {
    // In the real pipeline, description is cleaned before interpolation
    const template = '{{title}}{{description}}';
    const vars = {
      title: 'Fix bug',
      description: ': Step 1: do X Step 2: do Y Step 3: do Z',
    };
    const interpolated = interpolateTemplate(template, vars);
    const quoted = quoteArg(interpolated);

    expect(quoted).not.toContain('\n');
    expect(quoted).toContain('Fix bug');
    expect(quoted).toContain('Step 1: do X Step 2: do Y Step 3: do Z');
  });
});

