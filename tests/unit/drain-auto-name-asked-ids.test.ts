// ---------------------------------------------------------------------------
// Import the function under test
// ---------------------------------------------------------------------------

import { drainAutoNameAskedIds } from '../../src/main/ipc/handlers/task-crud';
import type { IpcContext } from '../../src/main/ipc/ipc-context';

// ---------------------------------------------------------------------------
// Helper: build a minimal IpcContext with a configurable configManager
// ---------------------------------------------------------------------------

function makeConfigManager(opts: {
  loadResult?: { autoNameAskedTaskIds?: string[] } | (() => { autoNameAskedTaskIds?: string[] });
  saveThrows?: boolean;
}) {
  const loadFn = typeof opts.loadResult === 'function'
    ? opts.loadResult
    : vi.fn(() => opts.loadResult ?? {});

  const saveFn = opts.saveThrows
    ? vi.fn(() => { throw new Error('disk full'); })
    : vi.fn();

  return {
    load: typeof opts.loadResult === 'function' ? opts.loadResult : loadFn,
    save: saveFn,
    getEffectiveConfig: vi.fn(() => ({})),
    saveProjectOverrides: vi.fn(),
    loadProjectOverrides: vi.fn(() => null),
  };
}

function makeContext(configManager: ReturnType<typeof makeConfigManager>): IpcContext {
  return {
    configManager,
    boardConfigManager: { getDefaultBaseBranch: vi.fn(() => null) },
    sessionManager: { setMaxConcurrent: vi.fn(), setShell: vi.fn(), setIdleTimeout: vi.fn() },
    projectRepo: { list: vi.fn(() => []) },
    shellResolver: { getAvailableShells: vi.fn(() => []), getDefaultShell: vi.fn(() => 'bash') },
    gitDetector: { detect: vi.fn(() => ({ found: false })) },
    mainWindow: {
      isDestroyed: vi.fn(() => false),
      webContents: { send: vi.fn() },
      minimize: vi.fn(), maximize: vi.fn(), unmaximize: vi.fn(),
      isMaximized: vi.fn(() => false), close: vi.fn(), isFocused: vi.fn(() => true),
      flashFrame: vi.fn(), isMinimized: vi.fn(() => false), restore: vi.fn(),
      show: vi.fn(), focus: vi.fn(), once: vi.fn(),
    },
    currentProjectPath: null,
    currentProjectId: null,
  } as unknown as IpcContext;
}

// ---------------------------------------------------------------------------
// Tests
// ---------------------------------------------------------------------------

describe('drainAutoNameAskedIds', () => {
  beforeEach(() => {
    capturedHandlers.clear();
  });

  it('removes matching IDs from autoNameAskedTaskIds and calls save with the filtered array', () => {
    const configManager = makeConfigManager({
      loadResult: { autoNameAskedTaskIds: ['task-1', 'task-2', 'task-3'] },
    });
    const context = makeContext(configManager);

    drainAutoNameAskedIds(context, ['task-1', 'task-3']);

    expect(configManager.save).toHaveBeenCalledTimes(1);
    const savedConfig = (configManager.save as ReturnType<typeof vi.fn>).mock.calls[0][0];
    expect(savedConfig.autoNameAskedTaskIds).toEqual(['task-2']);
  });

  it('is a no-op when autoNameAskedTaskIds field is absent from the config', () => {
    const configManager = makeConfigManager({ loadResult: {} });
    const context = makeContext(configManager);

    drainAutoNameAskedIds(context, ['task-1']);

    // save should NOT have been called - nothing to drain
    expect(configManager.save).not.toHaveBeenCalled();
  });

  it('is a no-op when autoNameAskedTaskIds is an empty array', () => {
    const configManager = makeConfigManager({
      loadResult: { autoNameAskedTaskIds: [] },
    });
    const context = makeContext(configManager);

    drainAutoNameAskedIds(context, ['task-1']);

    expect(configManager.save).not.toHaveBeenCalled();
  });

  it('is a no-op when no IDs in the input list match the stored entries', () => {
    const configManager = makeConfigManager({
      loadResult: { autoNameAskedTaskIds: ['task-a', 'task-b'] },
    });
    const context = makeContext(configManager);

    drainAutoNameAskedIds(context, ['task-x', 'task-y']);

    // next.length === current.length, so no save
    expect(configManager.save).not.toHaveBeenCalled();
  });

  it('is a no-op when the input list is empty', () => {
    const configManager = makeConfigManager({
      loadResult: { autoNameAskedTaskIds: ['task-1', 'task-2'] },
    });
    const context = makeContext(configManager);

    drainAutoNameAskedIds(context, []);

    // Early return before any load/save
    expect(configManager.save).not.toHaveBeenCalled();
  });

  it('swallows errors thrown by configManager.save() without propagating', () => {
    const configManager = makeConfigManager({
      loadResult: { autoNameAskedTaskIds: ['task-1'] },
      saveThrows: true,
    });
    const context = makeContext(configManager);

    // Should not throw
    expect(() => drainAutoNameAskedIds(context, ['task-1'])).not.toThrow();
  });

  it('swallows errors thrown by configManager.load() without propagating', () => {
    const configManager = makeConfigManager({
      loadResult: () => { throw new Error('config corrupted'); },
    });
    const context = makeContext(configManager);

    expect(() => drainAutoNameAskedIds(context, ['task-1'])).not.toThrow();
    expect(configManager.save).not.toHaveBeenCalled();
  });

  it('removes all matching IDs when the entire list is in the input', () => {
    const configManager = makeConfigManager({
      loadResult: { autoNameAskedTaskIds: ['task-1', 'task-2'] },
    });
    const context = makeContext(configManager);

    drainAutoNameAskedIds(context, ['task-1', 'task-2']);

    expect(configManager.save).toHaveBeenCalledTimes(1);
    const savedConfig = (configManager.save as ReturnType<typeof vi.fn>).mock.calls[0][0];
    expect(savedConfig.autoNameAskedTaskIds).toEqual([]);
  });
});
