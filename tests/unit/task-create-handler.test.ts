describe('TASK_CREATE handler', () => {
  let context: MockContext;
  let task: MockTask;
  let taskRepo: MockTaskRepo;
  let attachmentRepo: MockAttachmentRepo;
  let swimlaneRepo: MockSwimlaneRepo;
  let targetLane: MockSwimlane;

  beforeEach(() => {
    vi.clearAllMocks();
    capturedHandlers.clear();
    __resetSpawnProgressForTest();

    targetLane = createMockSwimlane('lane-doing', { auto_spawn: true });
    task = createMockTask('task-new', { swimlane_id: 'lane-doing' });
    taskRepo = createMockTaskRepo(task);
    attachmentRepo = createMockAttachmentRepo();
    swimlaneRepo = createMockSwimlaneRepo([targetLane]);
    context = createMockContext();

    mockGetProjectRepos.mockReturnValue({
      tasks: taskRepo,
      swimlanes: swimlaneRepo,
      actions: { getTransitionsFor: vi.fn(() => []) },
      attachments: attachmentRepo,
    });

    mockEnsureTaskWorktree.mockResolvedValue(null);
    mockEnsureTaskBranchCheckout.mockResolvedValue(undefined);

    const engine = createMockEngine();
    mockCreateTransitionEngine.mockReturnValue(engine);

    registerTaskCrudHandlers(context as never);
  });

  // =========================================================================
  // auto_spawn=false: skips entire lock block
  // =========================================================================

  it('skips worktree, transition, and auto-command when target lane has auto_spawn=false', async () => {
    const noSpawnLane = createMockSwimlane('lane-backlog', { auto_spawn: false });
    swimlaneRepo = createMockSwimlaneRepo([noSpawnLane]);
    const noSpawnTask = createMockTask('task-no-spawn', { swimlane_id: 'lane-backlog' });
    taskRepo = createMockTaskRepo(noSpawnTask);

    mockGetProjectRepos.mockReturnValue({
      tasks: taskRepo,
      swimlanes: swimlaneRepo,
      actions: { getTransitionsFor: vi.fn(() => []) },
      attachments: attachmentRepo,
    });

    const result = await callCreateHandler(context, {
      swimlane_id: 'lane-backlog',
      title: 'No spawn task',
    });

    expect(result).toMatchObject({ id: 'task-no-spawn' });
    expect(mockEnsureTaskWorktree).not.toHaveBeenCalled();
    expect(mockCreateTransitionEngine).not.toHaveBeenCalled();
    expect(mockSpawnAgent).not.toHaveBeenCalled();
  });

  it('skips lock block when currentProjectPath is null', async () => {
    context.currentProjectPath = null;
    capturedHandlers.clear();
    registerTaskCrudHandlers(context as never);

    const result = await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'No path task',
    });

    expect(result).toMatchObject({ id: 'task-new' });
    expect(mockEnsureTaskWorktree).not.toHaveBeenCalled();
    expect(mockCreateTransitionEngine).not.toHaveBeenCalled();
  });

  it('skips lock block when currentProjectId is null', async () => {
    context.currentProjectId = null;
    capturedHandlers.clear();
    registerTaskCrudHandlers(context as never);

    const result = await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'No project task',
    });

    expect(result).toMatchObject({ id: 'task-new' });
    expect(mockEnsureTaskWorktree).not.toHaveBeenCalled();
  });

  // =========================================================================
  // Worktree error branch
  // =========================================================================

  it('returns task without spawning when ensureTaskWorktree throws (lock released cleanly)', async () => {
    mockEnsureTaskWorktree.mockRejectedValue(new Error('git worktree add failed'));

    const result = await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Worktree error task',
    });

    expect(result).toMatchObject({ id: 'task-new' });
    expect(mockCreateTransitionEngine).not.toHaveBeenCalled();
    expect(mockSpawnAgent).not.toHaveBeenCalled();
  });

  it('tells the user the worktree step failed, instead of leaving a healthy-looking card', async () => {
    const worktreeError = new Error('git worktree add failed');
    mockEnsureTaskWorktree.mockRejectedValue(worktreeError);

    await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Worktree error task',
    });

    // Red-green: pre-fix this branch was `console.error` + `return`, so a task
    // created into a spawn column sat there with a null session and a null
    // worktree, indistinguishable from a healthy one (task #538).
    expect(mockNotifySpawnBlocked).toHaveBeenCalledTimes(1);
    const [, task, step, error] = mockNotifySpawnBlocked.mock.calls[0];
    expect((task as { id: string }).id).toBe('task-new');
    expect(step).toBe('worktree');
    expect(error).toBe(worktreeError);
  });

  // =========================================================================
  // Checkout error branch
  // =========================================================================

  it('returns task without spawning when ensureTaskBranchCheckout throws', async () => {
    mockEnsureTaskBranchCheckout.mockRejectedValue(new Error('branch locked by active session'));

    const result = await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Checkout error task',
    });

    expect(result).toMatchObject({ id: 'task-new' });
    expect(mockCreateTransitionEngine).not.toHaveBeenCalled();
    expect(mockSpawnAgent).not.toHaveBeenCalled();
  });

  it('tells the user the checkout step failed', async () => {
    mockEnsureTaskBranchCheckout.mockRejectedValue(new Error('branch locked by active session'));

    await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Checkout error task',
    });

    expect(mockNotifySpawnBlocked).toHaveBeenCalledTimes(1);
    expect(mockNotifySpawnBlocked.mock.calls[0][2]).toBe('checkout');
  });

  // =========================================================================
  // Create-into-spawn-column routes through the shared spawnAgent chokepoint
  //
  // A task created directly in a spawn column must take the SAME path as
  // every other spawn entry point (move, promote, MCP create, unarchive):
  // spawnAgent, whose preamble locks the Advanced overrides and resolves the
  // agent BEFORE the engine runs. Red-green: on the pre-consolidation handler
  // (its own executeTransition + lock + auto-command block), spawnAgent is
  // never called and this fails. See
  // .claude/rules/spawn-entry-point-parity.md.
  // =========================================================================

  it('routes through spawnAgent with "*" wildcard, the creation column as toLane, and NO settingsSourceLane', async () => {
    const engine = createMockEngine();
    mockCreateTransitionEngine.mockReturnValue(engine);

    await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Spawn routing task',
    });

    expect(mockSpawnAgent).toHaveBeenCalledTimes(1);
    const spawnArg = mockSpawnAgent.mock.calls[0][0] as {
      context: MockContext;
      engine: MockEngine;
      tasks: MockTaskRepo;
      task: { id: string };
      fromSwimlaneId: string;
      toLane: MockSwimlane;
      projectId: string;
      projectPath: string;
    };
    expect(spawnArg.task).toMatchObject({ id: 'task-new' });
    // No source column on creation - matches wildcard transitions.
    expect(spawnArg.fromSwimlaneId).toBe('*');
    // The creation column IS the destination (and, via spawnAgent's
    // settingsSourceLane fallback, the settings lane the lock resolves
    // against) - so settingsSourceLane must be OMITTED, not null: null would
    // mean "the settings lane no longer resolves" and skip the lane entirely.
    expect('settingsSourceLane' in spawnArg).toBe(false);
    expect(spawnArg.toLane).toBe(targetLane);
    // Project context threaded so the preamble sees project defaults.
    expect(spawnArg.projectId).toBe('proj-123');
    expect(spawnArg.projectPath).toBe('/mock/project');
    // The engine and repos the handler constructed are handed through.
    expect(spawnArg.engine).toBe(engine);
    expect(spawnArg.tasks).toBe(taskRepo);
  });

  it('returns the created task even when spawnAgent rejects', async () => {
    mockSpawnAgent.mockRejectedValueOnce(new Error('CLI not found'));

    const result = await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Spawn failure task',
    });

    expect(result).toMatchObject({ id: 'task-new' });
  });

  // =========================================================================
  // Spawn progress wiring (born-into-a-column spawns used to be silent)
  // =========================================================================

  it('threads onProgress + projectId into both git helpers and pushes their phases to the card', async () => {
    // The mocked helper stands in for the real one emitting 'fetching'; the
    // handler's createProgressCallback must resolve it and push over IPC.
    mockEnsureTaskWorktree.mockImplementation(async (
      _context: unknown, _task: unknown, _tasks: unknown, _path: unknown,
      options?: { onProgress?: (phase: string) => void },
    ) => {
      options?.onProgress?.('fetching');
      return null;
    });

    await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Progress task',
    });

    const worktreeOptions = mockEnsureTaskWorktree.mock.calls[0][4] as { onProgress?: unknown; projectId?: unknown };
    expect(typeof worktreeOptions.onProgress).toBe('function');
    expect(worktreeOptions.projectId).toBe('proj-123');
    const checkoutOptions = mockEnsureTaskBranchCheckout.mock.calls[0][3] as { onProgress?: unknown; projectId?: unknown };
    expect(typeof checkoutOptions.onProgress).toBe('function');
    expect(checkoutOptions.projectId).toBe('proj-123');

    expect(context.mainWindow.webContents.send).toHaveBeenCalledWith(
      IPC.TASK_SPAWN_PROGRESS, 'task-new', 'Fetching latest...',
    );
    // The finally cleared the label, so an HMR reconcile after the create
    // cannot strand the card on a stale phase.
    expect(getInFlightSpawnProgress()).toEqual({});
  });

  it('clears the in-flight label even when a git step fails', async () => {
    mockEnsureTaskWorktree.mockImplementation(async (
      _context: unknown, _task: unknown, _tasks: unknown, _path: unknown,
      options?: { onProgress?: (phase: string) => void },
    ) => {
      options?.onProgress?.('creating-worktree');
      throw new Error('git worktree add failed');
    });

    await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Progress cleanup task',
    });

    // The notifySpawnBlocked early-return still flows through the finally.
    expect(getInFlightSpawnProgress()).toEqual({});
  });

  // =========================================================================
  // Pending attachments
  // =========================================================================

  it('saves pending attachments when provided', async () => {
    const pendingAttachments = [
      { filename: 'screenshot.png', data: 'base64data', media_type: 'image/png' },
    ];

    await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Task with attachment',
      pendingAttachments,
    });

    expect(attachmentRepo.add).toHaveBeenCalledWith(
      '/mock/project',
      'task-new',
      'screenshot.png',
      'base64data',
      'image/png',
    );
  });

  it('does NOT save attachments when pendingAttachments is empty', async () => {
    await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Task no attachments',
      pendingAttachments: [],
    });

    expect(attachmentRepo.add).not.toHaveBeenCalled();
  });

  it('does NOT save attachments when currentProjectPath is null', async () => {
    context.currentProjectPath = null;
    capturedHandlers.clear();
    registerTaskCrudHandlers(context as never);

    const pendingAttachments = [
      { filename: 'photo.jpg', data: 'data', media_type: 'image/jpeg' },
    ];

    await callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Task no project path',
      pendingAttachments,
    });

    expect(attachmentRepo.add).not.toHaveBeenCalled();
  });

  // =========================================================================
  // withTaskLock engagement: concurrent TASK_CREATE for the same task id
  // =========================================================================

  it('serializes concurrent withTaskLock calls for the same task id', async () => {
    // Use the hold pattern from task-lifecycle-lock.test.ts:
    // first invocation holds until released; second must wait.
    let releaseFirst!: () => void;
    const firstHold = new Promise<void>((resolve) => {
      releaseFirst = resolve;
    });
    const entryOrder: number[] = [];

    mockEnsureTaskWorktree.mockImplementation(async () => {
      entryOrder.push(entryOrder.length);
      if (entryOrder.length === 1) {
        await firstHold;
      }
    });

    // Both invocations share the same task.id returned by tasks.create.
    // That id is what withTaskLock keys on.
    taskRepo.getById.mockReturnValue({ ...task, session_id: null });

    const engine = createMockEngine();
    mockCreateTransitionEngine.mockReturnValue(engine);

    const first = callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'First concurrent task',
    });
    const second = callCreateHandler(context, {
      swimlane_id: 'lane-doing',
      title: 'Second concurrent task',
    });

    // Only the first invocation should have entered ensureTaskWorktree yet
    await Promise.resolve();
    expect(entryOrder).toHaveLength(1);

    releaseFirst();
    await Promise.all([first, second]);

    // Both entered, in submission order
    expect(entryOrder).toHaveLength(2);
    expect(entryOrder).toEqual([0, 1]);
  });
});
