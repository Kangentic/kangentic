// ---------------------------------------------------------------------------
// Import under test (after all mocks)
// ---------------------------------------------------------------------------

import { registerTaskCrudHandlers } from '../../src/main/ipc/handlers/task-crud';
import { IPC } from '../../src/shared/ipc-channels';

// ---------------------------------------------------------------------------
// Fixtures
// ---------------------------------------------------------------------------

const CURRENT_PROJECT_ID = 'proj-1';
const CURRENT_PROJECT_PATH = '/mock/project-one';
const OTHER_PROJECT_ID = 'proj-2';
const OTHER_PROJECT_PATH = '/mock/project-two';
const TASK_ID = 'task-to-delete';
const MAIN_WINDOW_WEB_CONTENTS_ID = 1;

/** The IPC event of a write made from the pop-out Agent Monitor. */
const FROM_OTHER_WINDOW = { sender: { id: 2, isDestroyed: () => false } };
/** The IPC event of a write made from the main window itself. */
const FROM_MAIN_WINDOW = { sender: { id: MAIN_WINDOW_WEB_CONTENTS_ID, isDestroyed: () => false } };

function createContext() {
  const send = vi.fn();
  return {
    currentProjectId: CURRENT_PROJECT_ID,
    currentProjectPath: CURRENT_PROJECT_PATH,
    // resolveProjectContext looks a non-current project's path up here.
    projectRepo: {
      getById: vi.fn((projectId: string) => (projectId === OTHER_PROJECT_ID
        ? { id: projectId, path: OTHER_PROJECT_PATH }
        : undefined)),
    },
    mainWindow: {
      isDestroyed: vi.fn(() => false),
      webContents: { id: MAIN_WINDOW_WEB_CONTENTS_ID, send },
    },
    boardEvents: { emitBoardChanged: vi.fn() },
    // Read by the drain of the "auto-name asked" set after a delete that went through.
    configManager: { load: vi.fn(() => ({})), save: vi.fn() },
    sessionManager: {},
  };
}

let context: ReturnType<typeof createContext>;
let tasks: { getById: ReturnType<typeof vi.fn>; delete: ReturnType<typeof vi.fn> };
let attachments: { deleteByTaskId: ReturnType<typeof vi.fn> };
let task: Record<string, unknown>;

/** Invoke the registered handler the way the preload does: event, task id, then the trailing project id (if any). */
function invokeDelete(event: unknown, ...trailingArguments: unknown[]): Promise<unknown> {
  const handler = shared.ipcHandlers.get(IPC.TASK_DELETE);
  if (!handler) throw new Error('TASK_DELETE handler not registered');
  return Promise.resolve(handler(event, TASK_ID, ...trailingArguments));
}

/** Every TASK_CHANGED_IN_OTHER_WINDOW push the main window received. */
function otherWindowPushes(): unknown[][] {
  return context.mainWindow.webContents.send.mock.calls
    .filter((call: unknown[]) => call[0] === IPC.TASK_CHANGED_IN_OTHER_WINDOW);
}

beforeEach(() => {
  vi.clearAllMocks();
  shared.ipcHandlers.clear();

  // No workflow: the wake and notify after a successful delete have nothing to do.
  task = { id: TASK_ID, title: 'Delete me', workflow_id: null, workflow_project_id: null };
  tasks = { getById: vi.fn(() => task), delete: vi.fn() };
  attachments = { deleteByTaskId: vi.fn() };
  // clearAllMocks keeps implementations: re-arm the ones a test may replace.
  shared.getProjectRepos.mockReset();
  shared.getProjectRepos.mockReturnValue({ tasks, attachments });
  shared.cleanupTaskResources.mockReset();
  shared.cleanupTaskResources.mockResolvedValue(undefined);

  context = createContext();
  registerTaskCrudHandlers(context as never);
});

// ---------------------------------------------------------------------------
// Tests
// ---------------------------------------------------------------------------

describe('TASK_DELETE announces the write to the main window', () => {
  it('deletes in the stamped project and pushes its id once when another window deletes', async () => {
    await invokeDelete(FROM_OTHER_WINDOW, OTHER_PROJECT_ID);

    expect(shared.getProjectRepos).toHaveBeenCalledWith(context, OTHER_PROJECT_ID);
    expect(attachments.deleteByTaskId).toHaveBeenCalledWith(TASK_ID);
    expect(shared.cleanupTaskResources).toHaveBeenCalledTimes(1);
    const [, cleanedTask, cleanedTasks, cleanedProjectId, cleanedProjectPath] = shared.cleanupTaskResources.mock.calls[0] as unknown[];
    expect(cleanedTask).toBe(task);
    expect(cleanedTasks).toBe(tasks);
    expect(cleanedProjectId).toBe(OTHER_PROJECT_ID);
    expect(cleanedProjectPath).toBe(OTHER_PROJECT_PATH);
    expect(tasks.delete).toHaveBeenCalledWith(TASK_ID);

    expect(otherWindowPushes()).toEqual([[IPC.TASK_CHANGED_IN_OTHER_WINDOW, OTHER_PROJECT_ID]]);
  });

  it('pushes the resolved current project id, not the missing request, when no id was stamped', async () => {
    // Announcing the raw argument would hand the helper null, which it treats as
    // "no project" and drops: the board would never hear of the delete.
    await invokeDelete(FROM_OTHER_WINDOW, null);

    expect(shared.getProjectRepos).toHaveBeenCalledWith(context, CURRENT_PROJECT_ID);
    expect(tasks.delete).toHaveBeenCalledWith(TASK_ID);
    expect(otherWindowPushes()).toEqual([[IPC.TASK_CHANGED_IN_OTHER_WINDOW, CURRENT_PROJECT_ID]]);
  });

  it('still pushes once, and still rejects with the cleanup error, when the cleanup fails after the attachments were deleted', async () => {
    // Red case: the shape before this change was
    //   await withTaskLock(...);
    //   drainAutoNameAskedIds(...); wakeWorkflowEngine(); notifyWorkflowOfTask(...);
    //   announceTaskWrite(context, event, resolvedProjectId, ...);
    // When cleanupTaskResources rejects, the lock rejects, the `await` throws,
    // and the announce line is never reached: zero pushes, so the one-push
    // assertion below fails. The `finally` is what makes it fire on this path.
    const cleanupError = new Error('worktree removal timed out');
    shared.cleanupTaskResources.mockRejectedValue(cleanupError);

    await expect(invokeDelete(FROM_OTHER_WINDOW, OTHER_PROJECT_ID)).rejects.toBe(cleanupError);

    // The write did commit before the failure: the attachments are gone, and the
    // task row survives, so the card under the main window's board is stale.
    expect(attachments.deleteByTaskId).toHaveBeenCalledWith(TASK_ID);
    expect(tasks.delete).not.toHaveBeenCalled();
    expect(otherWindowPushes()).toEqual([[IPC.TASK_CHANGED_IN_OTHER_WINDOW, OTHER_PROJECT_ID]]);
  });

  it('sends nothing for a delete made from the main window itself', async () => {
    await invokeDelete(FROM_MAIN_WINDOW, OTHER_PROJECT_ID);

    expect(tasks.delete).toHaveBeenCalledWith(TASK_ID);
    expect(otherWindowPushes()).toEqual([]);
  });

  it('sends nothing for a failed delete made from the main window itself', async () => {
    const cleanupError = new Error('worktree removal timed out');
    shared.cleanupTaskResources.mockRejectedValue(cleanupError);

    await expect(invokeDelete(FROM_MAIN_WINDOW, OTHER_PROJECT_ID)).rejects.toBe(cleanupError);

    expect(otherWindowPushes()).toEqual([]);
  });
});

describe('TASK_DELETE announces the write on the board-changed bus', () => {
  it('emits task-deleted for the stamped project once the row is gone, for a delete from the main window', async () => {
    // A paired phone is not the main window, so the board's own delete must
    // still reach it. The row is already gone when the event fires, so the
    // snapshot the phone re-reads on it no longer lists the card.
    // Recorded, not asserted, inside the listener. The helper swallows a
    // listener's throw, so an expect there could never fail the test.
    let rowDeletedAtEmit: boolean | undefined;
    context.boardEvents.emitBoardChanged.mockImplementation(() => {
      rowDeletedAtEmit = tasks.delete.mock.calls.length > 0;
    });

    await invokeDelete(FROM_MAIN_WINDOW, OTHER_PROJECT_ID);

    expect(rowDeletedAtEmit).toBe(true);
    expect(context.boardEvents.emitBoardChanged.mock.calls).toEqual([
      [{ projectId: OTHER_PROJECT_ID, change: 'task-deleted', ids: [TASK_ID] }],
    ]);
  });

  it('still emits once when the cleanup fails after the attachments were deleted', async () => {
    const cleanupError = new Error('worktree removal timed out');
    shared.cleanupTaskResources.mockRejectedValue(cleanupError);

    await expect(invokeDelete(FROM_MAIN_WINDOW, OTHER_PROJECT_ID)).rejects.toBe(cleanupError);

    expect(context.boardEvents.emitBoardChanged).toHaveBeenCalledTimes(1);
  });
});
