/**
 * TASK_SET_DETAIL_VIEW_STATE never creates a project's database.
 *
 * A project delete closes its tasks' Changes pop-outs (`closeTaskWindows`), and
 * the renderer answers each close by saving that task's detail view on a
 * debounce that fires after the delete has removed the database. A handler that
 * opened the database with `getProjectDb` migrated a new, empty file for the
 * deleted project. It now goes through `getExistingProjectDb`, which opens only
 * a file that is there.
 *
 * Real: `registerTaskCrudHandlers`, `resolveProjectContext`.
 * Doubled: the database module, the task repository, and the task-crud
 * dependencies that need Electron, git, or a database.
 */

import { describe, it, expect, vi, beforeEach } from 'vitest';

const shared = vi.hoisted(() => ({
  ipcHandlers: new Map<string, (...args: unknown[]) => unknown>(),
  getExistingProjectDb: vi.fn((_projectId: string): object | null => null),
  getProjectDb: vi.fn((_projectId: string) => ({})),
  setDetailViewState: vi.fn((_taskId: string, _state: string | null) => {}),
}));

vi.mock('electron', () => ({
  ipcMain: {
    handle: vi.fn((channel: string, handler: (...args: unknown[]) => unknown) => {
      shared.ipcHandlers.set(channel, handler);
    }),
  },
}));

vi.mock('simple-git', () => ({ simpleGit: vi.fn(() => ({})) }));

vi.mock('../../src/main/db/database', () => ({
  getExistingProjectDb: (projectId: string) => shared.getExistingProjectDb(projectId),
  getProjectDb: (projectId: string) => shared.getProjectDb(projectId),
}));
vi.mock('../../src/main/db/repositories/task-repository', () => ({
  TaskRepository: class {
    setDetailViewState(taskId: string, state: string | null): void {
      shared.setDetailViewState(taskId, state);
    }
  },
}));
vi.mock('../../src/main/db/repositories/session-repository', () => ({ SessionRepository: class {} }));
vi.mock('../../src/main/git/worktree-manager', () => ({ WorktreeManager: class {} }));
vi.mock('../../src/main/git/git-checks', () => ({ isAutoGeneratedBranch: vi.fn(() => false) }));

vi.mock('../../src/main/ipc/helpers', () => ({
  getProjectRepos: vi.fn(),
  cleanupTaskResources: vi.fn(),
  ensureTaskWorktree: vi.fn(),
  ensureTaskBranchCheckout: vi.fn(),
  notifySpawnBlocked: vi.fn(),
  createTransitionEngine: vi.fn(),
  spawnAgent: vi.fn(),
}));

vi.mock('../../src/main/agent/shared', () => ({
  interpolateTemplate: vi.fn((template: string) => template),
  resolveBridgeScript: vi.fn(() => '/mock/bridge.js'),
  execVersion: vi.fn(async () => '1.0.0'),
}));

vi.mock('../../src/main/ipc/handlers/task-move', () => ({
  handleTaskMove: vi.fn(async () => {}),
}));

vi.mock('../../src/main/pr/pr-linking', () => ({
  linkPR: vi.fn(),
  autoLinkPRForTask: vi.fn(),
}));

import { registerTaskCrudHandlers } from '../../src/main/ipc/handlers/task-crud';
import { IPC } from '../../src/shared/ipc-channels';

const DELETED_PROJECT_ID = 'proj-deleted';

function registerHandlers(): (...args: unknown[]) => unknown {
  shared.ipcHandlers.clear();
  const context = {
    currentProjectId: 'proj-current',
    currentProjectPath: '/mock/project-current',
    projectRepo: { getById: vi.fn(() => undefined) },
  };
  registerTaskCrudHandlers(context as never);
  const handler = shared.ipcHandlers.get(IPC.TASK_SET_DETAIL_VIEW_STATE);
  if (!handler) throw new Error('TASK_SET_DETAIL_VIEW_STATE was not registered');
  return handler;
}

describe('TASK_SET_DETAIL_VIEW_STATE', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    shared.getExistingProjectDb.mockReturnValue(null);
  });

  it('drops the save, and creates no database, when the project database is gone', () => {
    const handler = registerHandlers();

    handler({}, 'task-1', { changesOpen: false }, DELETED_PROJECT_ID);

    expect(shared.getExistingProjectDb).toHaveBeenCalledWith(DELETED_PROJECT_ID);
    expect(shared.getProjectDb).not.toHaveBeenCalled();
    expect(shared.setDetailViewState).not.toHaveBeenCalled();
  });

  it('saves the view into the database that exists, against the stamped project', () => {
    shared.getExistingProjectDb.mockReturnValue({});
    const handler = registerHandlers();

    handler({}, 'task-1', { dividerRatio: 0.4 }, 'proj-live');

    expect(shared.getExistingProjectDb).toHaveBeenCalledWith('proj-live');
    expect(shared.setDetailViewState).toHaveBeenCalledWith('task-1', JSON.stringify({ dividerRatio: 0.4 }));
  });
});
