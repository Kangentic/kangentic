/**
 * Unit test for the remote-execution worktree skip added to
 * `ensureTaskWorktree` (task-git.ts): a task whose resolved agent is set to
 * 'remote' execution for the current project must not get a local worktree
 * created - the agent runs against the configured server directory instead.
 *
 * Also covers the `hasCommits` early-return guard `ensureTaskBranchCheckout`
 * keeps for itself: a repo with an unborn HEAD (no commits) has nothing to
 * branch from, so branch checkout would fail on the ref - the guard skips
 * that work entirely rather than letting the failure propagate.
 * `ensureTaskWorktree`'s own no-commits (and base-branch-resolution) guard
 * moved into `WorktreeManager.ensureWorktree` so every caller shares it; it
 * is covered by `tests/unit/worktree-base-branch.test.ts` instead, since
 * `WorktreeManager` is mocked away entirely in this file.
 *
 * WorktreeManager and git-checks are mocked entirely so this test never
 * touches git or the filesystem; it only asserts whether `ensureWorktree()` /
 * `checkoutBranch()` were called.
 */
import { describe, it, expect, vi, beforeEach } from 'vitest';
import path from 'node:path';
import { ensureTaskWorktree, ensureTaskBranchCheckout } from '../../src/main/ipc/helpers/task-git';
import type { IpcContext } from '../../src/main/ipc/ipc-context';
import type { Task, AppConfig, Project } from '../../src/shared/types';
import { DEFAULT_CONFIG } from '../../src/shared/types';

const ensureWorktreeMock = vi.fn().mockResolvedValue({ worktreePath: '/local/worktree/feature-x-abcd1234', branchName: 'feature-x' });
const checkoutBranchMock = vi.fn().mockResolvedValue(undefined);
const withLockMock = vi.fn((fn: () => unknown) => fn());

vi.mock('../../src/main/git/worktree-manager', () => ({
  WorktreeManager: vi.fn().mockImplementation(function MockWorktreeManager(this: Record<string, unknown>) {
    this.withLock = withLockMock;
    this.ensureWorktree = ensureWorktreeMock;
    this.checkoutBranch = checkoutBranchMock;
  }),
}));

// hasCommits defaults to true (a normal, already-committed repo) so the pre-existing
// remote-execution-skip tests below exercise ONLY that branch, not this guard. Each
// hasCommits-guard test overrides it explicitly.
const hasCommitsMock = vi.fn().mockResolvedValue(true);
const isGitRepoMock = vi.fn().mockReturnValue(true);
const isAutoGeneratedBranchMock = vi.fn().mockReturnValue(false);

vi.mock('../../src/main/git/git-checks', () => ({
  hasCommits: (...args: unknown[]) => hasCommitsMock(...args),
  isGitRepo: (...args: unknown[]) => isGitRepoMock(...args),
  isAutoGeneratedBranch: (...args: unknown[]) => isAutoGeneratedBranchMock(...args),
  isInsideWorktree: vi.fn(() => true),
}));

// The base-branch checkout arm now freshens the checkout (simple-git instance
// plus a throttled fetch) before delegating to checkoutBranch. Neither belongs
// to this file's subject, so both are stubbed inert: the real simpleGit throws
// on this file's fictional '/project' cwd, and the fetch stub returns the bare
// branch name (the failure shape), which keeps the fast-forward path dormant.
vi.mock('simple-git', () => {
  const gitFactory = vi.fn(() => ({ raw: vi.fn(async () => '') }));
  return { simpleGit: gitFactory, default: gitFactory };
});

vi.mock('../../src/main/git/fetch-throttle', () => ({
  fetchIfStale: vi.fn(async (_git: unknown, _path: string, branch: string) => branch),
}));

