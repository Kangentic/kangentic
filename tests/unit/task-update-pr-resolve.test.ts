/**
 * Unit tests for the link-time PR resolve on the TASK_UPDATE IPC handler.
 *
 * TASK_UPDATE is the main-process sink for the task-detail edit form: its
 * `buildPrFields` writes pr_url + pr_number with pr_state deliberately null, so
 * a stale terminal state cannot freeze a re-pointed link. Nothing then refilled
 * that state promptly, which left the board card showing a bare PR pill with no
 * state chip until the background sweep ran. The handler now fires a forced
 * resolve right after the write.
 *
 * Pattern mirrors task-create-handler.test.ts: capture the function registered
 * with ipcMain.handle and invoke it directly, with every dependency mocked so
 * no Electron binary or real filesystem is needed.
 *
 * Covers:
 *   - a write that SETS a link resolves, forced and preserving the link
 *   - a write that CLEARS a link does not resolve (the ladder's branch/commit
 *     tiers would re-link the task and bounce the clear straight back)
 *   - an edit that does not touch the PR fields does not resolve
 *   - the renderer's explicit projectId is what the resolve is routed by
 *   - a failing resolve never fails the update
 */

